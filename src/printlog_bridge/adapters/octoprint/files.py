"""What the bridge reads of an OctoPrint job's file: the estimates, a thumbnail, the slicer's
settings. Never the toolpaths, and never more than once per job.

- `/api/job` already has OctoPrint's own analysis of the file: `estimatedPrintTime` and, per
  tool, `filament.tool<N>.length` (mm) and `volume` (cm³). That is all there is for a file on
  the printer's SD card (`origin` `sdcard`), which OctoPrint can't read.
- For a file OctoPrint holds (`origin` `local`), two byte ranges of its download
  (`/downloads/files/local/<path>`, which honors `Range`): the first `HEAD_BYTES`, for the
  slicer's header and its embedded thumbnails (PrusaSlicer's, OrcaSlicer's and Cura's
  `; thumbnail begin <w>x<h> <length>` blocks of base64), and the last `TAIL_BYTES`, for the
  `; key = value` block after the G-code: the slicer's `filament used [g]` per tool (OctoPrint
  knows no weights) and `[mm]` (preferred to OctoPrint's analysis, which a firmware retraction
  or a relative-extrusion quirk can throw off), `printer_model`, and the settings.
- Without an embedded thumbnail, the PrusaSlicer Thumbnails plugin's, when the file's entry in
  `/api/files` names one (`thumbnail`).
"""

from __future__ import annotations

import asyncio
import base64
import binascii
import logging
import re
from collections.abc import Mapping
from typing import Any

import aiohttp

from printlog_bridge.adapters.prusalink.bgcode import parse_ini
from printlog_bridge.adapters.prusalink.files import JobFile, facts_from_meta
from printlog_bridge.core.events import SlicerFile, SlicerMetadata
from printlog_bridge.core.images import image_type
from printlog_bridge.core.slicer_settings import config_block_from, header_from
from printlog_bridge.core.status import PrinterReport

from .client import OctoPrintClient, Refused, download_path, file_path

log = logging.getLogger(__name__)

HEAD_BYTES = 256 * 1024
"""Thumbnails sit right after the header; a large one is a few hundred KB of base64."""
TAIL_BYTES = 512 * 1024
MAX_THUMBNAIL_BYTES = 2 * 1024 * 1024
READ_TIMEOUT_S = 60.0
LOCAL = "local"
_THUMBNAIL = re.compile(
    r"^; thumbnail(?:_(PNG|JPG|QOI))? begin (\d+)x(\d+) \d+\s*$(.*?)^; thumbnail(?:_\w+)? end",
    re.MULTILINE | re.DOTALL,
)
_GENERATOR = re.compile(r"generated by (\S+)(?: (?:v|version )?(\d[\w.\-+]*))?", re.IGNORECASE)


def tool_lengths(job: Mapping[str, Any]) -> dict[int, float]:
    """OctoPrint's analysis: millimeters per tool (`filament.tool<N>.length`), tools that use
    nothing left out."""
    filament = job.get("filament")
    if not isinstance(filament, Mapping):
        return {}
    lengths: dict[int, float] = {}
    for key, tool in filament.items():
        match = re.fullmatch(r"tool(\d+)", str(key))
        if match is None or not isinstance(tool, Mapping):
            continue
        length = tool.get("length")
        if isinstance(length, (int, float)) and not isinstance(length, bool) and length > 0:
            lengths[int(match.group(1))] = round(float(length), 1)
    return dict(sorted(lengths.items()))


def from_analysis(job: Mapping[str, Any]) -> JobFile:
    """What `/api/job`'s `job` says of its file, without reading it."""
    seconds = job.get("estimatedPrintTime")
    duration = (
        float(seconds)
        if isinstance(seconds, (int, float)) and not isinstance(seconds, bool) and seconds > 0
        else None
    )
    return JobFile(mm=tool_lengths(job), duration_s=duration)


class OctoPrintFiles:
    def __init__(
        self,
        printer: str,
        client: OctoPrintClient,
        report: PrinterReport | None = None,
        *,
        enabled: bool = True,
        timeout: float = READ_TIMEOUT_S,
    ) -> None:
        self.printer = printer
        self.client = client
        self.report = report
        self.enabled = enabled
        self.timeout = timeout

    async def read(self, job: Mapping[str, Any]) -> JobFile:
        """The file of `job` (`/api/job`'s `job`)."""
        found = from_analysis(job)
        file = job.get("file") if isinstance(job.get("file"), Mapping) else {}
        origin, path = file.get("origin"), file.get("path")  # type: ignore[union-attr]
        size = file.get("size")  # type: ignore[union-attr]
        if not self.enabled or origin != LOCAL or not isinstance(path, str) or not path:
            return found
        try:
            await asyncio.wait_for(self._read(found, path, size), self.timeout)
        except Refused as e:
            log.warning("[printer %s] can't read the job's file: %s", self.printer, e)
        except asyncio.TimeoutError:
            log.warning(
                "[printer %s] the job's file didn't arrive within %gs: logged with OctoPrint's "
                "estimates only", self.printer, self.timeout,
            )  # fmt: skip
        except (aiohttp.ClientError, OSError, ValueError) as e:
            log.warning(
                "[printer %s] can't read the job's file (%s): logged with OctoPrint's estimates "
                "only", self.printer, e,
            )  # fmt: skip
        return found

    async def _read(self, found: JobFile, path: str, size: Any) -> None:
        url = download_path(LOCAL, path)
        size = size if isinstance(size, int) and size > 0 else None
        head = await self._range(url, 0, HEAD_BYTES if size is None else min(HEAD_BYTES, size))
        tail = b""
        if size is not None and size > len(head):
            tail = await self._range(url, max(len(head), size - TAIL_BYTES), size)
        block = config_block_from(tail, starts_mid_line=True, after_gcode=True) if tail else None
        if not tail and size is not None and size <= HEAD_BYTES:
            block = config_block_from(head, after_gcode=True)  # a small file: all of it read
        header = header_from(head)
        settings = parse_ini(block.encode()) if block else {}
        facts = facts_from_meta(settings)
        found.grams = facts.grams
        found.mm = facts.mm or found.mm  # the slicer's own count, when it wrote one
        found.duration_s = found.duration_s or facts.duration_s
        found.printer_model = facts.printer_model
        if block or header:
            found.settings = SlicerFile(header=header, config_block=block)
            found.metadata = metadata_from(header, settings)
        found.thumbnail = thumbnail_from(head) or await self._plugin_thumbnail(path)

    async def _range(self, url: str, start: int, end: int) -> bytes:
        """Bytes `start` to `end` (exclusive), never more: a server that ignores `Range` is
        read only as far as the range's length, and then only when it starts at 0."""
        if end <= start:
            return b""
        headers = {"Range": f"bytes={start}-{end - 1}"}
        async with self.client.stream(url, headers) as response:
            if response.status == 206:
                pass
            elif response.status == 200 and start == 0:
                pass  # the whole file: its start is what was asked for
            elif response.status == 200:
                raise ValueError("OctoPrint ignored the range, so the file's end wasn't read")
            else:
                raise ValueError(f"HTTP {response.status} for the job's file")
            data = bytearray()
            async for chunk in response.content.iter_chunked(64 * 1024):
                data += chunk
                if len(data) >= end - start:
                    break
            response.close()
            return bytes(data[: end - start])

    async def _plugin_thumbnail(self, path: str) -> bytes | None:
        """The PrusaSlicer Thumbnails plugin's picture, when the file's entry names one."""
        try:
            status, entry = await self.client.get_json(file_path(LOCAL, path))
            thumbnail = (
                entry.get("thumbnail") if status == 200 and isinstance(entry, Mapping) else None
            )
            if not isinstance(thumbnail, str) or not thumbnail or "://" in thumbnail:
                return None
            data = bytearray()
            async with self.client.stream("/" + thumbnail.lstrip("/")) as response:
                if response.status != 200:
                    return None
                async for chunk in response.content.iter_chunked(64 * 1024):
                    data += chunk
                    if len(data) > MAX_THUMBNAIL_BYTES:
                        return None
        except (aiohttp.ClientError, OSError, Refused, asyncio.TimeoutError) as e:
            log.info("[printer %s] no thumbnail from OctoPrint: %s", self.printer, e)
            return None
        return bytes(data) if image_type(bytes(data)) else None


def thumbnail_from(head: bytes) -> bytes | None:
    """The largest PNG or JPEG thumbnail embedded in a G-code file's start."""
    text = head.decode("utf-8", errors="replace")
    best: tuple[int, bytes] | None = None
    for match in _THUMBNAIL.finditer(text):
        if match.group(1) == "QOI":
            continue
        encoded = "".join(line.lstrip("; ").strip() for line in match.group(4).splitlines())
        try:
            data = base64.b64decode(encoded, validate=True)
        except (binascii.Error, ValueError):
            continue
        if image_type(data) is None or len(data) > MAX_THUMBNAIL_BYTES:
            continue
        area = int(match.group(2)) * int(match.group(3))
        if best is None or area > best[0]:
            best = (area, data)
    return best[1] if best else None


def metadata_from(header: str | None, settings: Mapping[str, str]) -> SlicerMetadata:
    slicer = version = None
    if header:
        match = _GENERATOR.search(header.splitlines()[0])
        if match:
            slicer, version = match.group(1), match.group(2)
    return SlicerMetadata(
        slicer=slicer,
        slicer_version=version,
        layer_height_mm=_first_number(settings.get("layer_height")),
        first_layer_height_mm=_first_number(settings.get("first_layer_height")),
        nozzle_diameter_mm=_first_number(settings.get("nozzle_diameter")),
        filament_name=_first_text(settings.get("filament_settings_id")),
        filament_type=_first_text(settings.get("filament_type")),
        first_layer_nozzle_temperature_c=_first_number(settings.get("first_layer_temperature")),
        first_layer_bed_temperature_c=_first_number(settings.get("first_layer_bed_temperature")),
    )


def _first_number(value: Any) -> float | None:
    if not isinstance(value, str):
        return None
    first = re.split(r"[,;]", value)[0].strip().rstrip("%")
    try:
        number = float(first)
    except ValueError:
        return None
    return number if number == number else None


def _first_text(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    first = re.split(r"[;,]", value)[0].strip().strip('"')
    return first or None
