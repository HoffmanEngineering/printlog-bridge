"""Real prints on a simulated Klipper printer, logged by the bridge. `pytest -m integration`.

Klipper runs the G-code on a simulated board, so Moonraker's history, its timings and
`filament_used` are the real thing. The 3D Print Log API is the in-process fake.
These are #4's acceptance criteria.
"""

from __future__ import annotations

import asyncio
import contextlib
from pathlib import Path

import bridge_helpers as helpers
import pytest
from bridge_helpers import write_config
from fake_moonraker import FakeMoonraker
from fake_printlog_api import FakePrintLogApi

pytestmark = [pytest.mark.integration, pytest.mark.klipper]

SQUARE = ["G1 X120 E10", "G1 Y120 E10", "G1 X20 E10", "G1 Y20 E10"]


def gcode(laps: int, speed: int = 3000) -> str:
    """A PrusaSlicer-style file: `laps` squares, 40 mm of filament each."""
    moves = "\n".join(SQUARE * laps)
    filament = 40 * laps
    return (
        "; generated by PrusaSlicer 2.7.1+linux-x64-GTK3 on 2026-10-10 at 09:30:00 UTC\n"
        "G28\nG90\nM83\nG1 Z1 F600\nG1 X20 Y20 F6000\n"
        f"G1 F{speed}\n{moves}\n"
        f"; filament used [mm] = {filament:.2f}\n"
        f"; filament used [g] = {filament * 0.003:.2f}\n"
        "; estimated printing time (normal mode) = 1m 5s\n"
    )


async def ask(printer, method: str, *args):
    """A call to the printer's HTTP API, off the event loop the bridge runs on."""
    return await asyncio.to_thread(getattr(printer, method), *args)


@contextlib.asynccontextmanager
async def logging_to_api(tmp_path: Path, printer):
    api = FakePrintLogApi()
    config = write_config(tmp_path, printer.url, await api.start())
    try:
        yield api, config
    except BaseException as e:
        # What each side saw, since a timeout alone says nothing about why.
        jobs = await ask(printer, "jobs")
        state = await ask(printer, "print_state")
        klippy = await ask(printer, "klippy_log")
        raise AssertionError(
            f"{e!r}\nprinter: {state}\nhistory: {jobs}\nAPI requests: {api.requests}\n"
            f"klippy.log:\n{klippy}"
        ) from e
    finally:
        await api.close()


@contextlib.asynccontextmanager
async def bridge(config: Path, printer):
    async def connected():
        return bool(await ask(printer, "agents"))

    async def disconnected():
        return not await ask(printer, "agents")

    async with helpers.bridge(config, connected, disconnected, timeout=30) as task:
        yield task


async def until(condition, timeout: float = 120) -> None:
    await helpers.until(condition, timeout)


def test_a_completed_print_is_logged_with_moonrakers_numbers(tmp_path, printer):
    async def scenario():
        await ask(printer, "upload", "shelf_bracket_0.2mm_PLA_MK4_1m5s.gcode", gcode(laps=2))
        async with logging_to_api(tmp_path, printer) as (api, config):
            async with bridge(config, printer):
                await ask(printer, "start_print", "shelf_bracket_0.2mm_PLA_MK4_1m5s.gcode")
                await until(lambda: api.prints)
                printing = dict(api.prints[1])
                await until(lambda: api.prints[1]["status"] != 2)
            [job] = [j for j in await ask(printer, "jobs") if j["filename"].startswith("shelf")]
            return printing, api.prints[1], job

    printing, done, job = asyncio.run(scenario())

    assert printing["status"] == 2  # Printing
    assert printing["title"] == "Shelf Bracket"
    assert printing["estimatedPrintTimeInSeconds"] == 65
    assert done["status"] == 3  # Success
    assert job["status"] == "completed"
    assert done["printTimeInSeconds"] == round(job["print_duration"])
    [row] = done["filamentUsage"]
    assert row["estimatedLengthInM"] == 0.08
    assert job["filament_used"] == pytest.approx(80, rel=0.02)
    assert row["lengthInM"] * 1000 == pytest.approx(job["filament_used"], rel=0.02)


def test_a_cancelled_print_is_logged_cancelled(tmp_path, printer):
    async def scenario():
        await ask(printer, "upload", "long.gcode", gcode(laps=20, speed=600))
        async with logging_to_api(tmp_path, printer) as (api, config):
            async with bridge(config, printer):
                await ask(printer, "start_print", "long.gcode")
                await until(lambda: api.prints)
                await ask(printer, "cancel")
                await until(lambda: api.prints[1]["status"] != 2)
            return api.prints[1]

    assert asyncio.run(scenario())["status"] == 4  # Cancelled


def test_a_print_that_ends_while_the_bridge_is_down_is_completed_once(tmp_path, printer):
    """Kill the bridge mid-print, restart it after the print ends: one correct print."""

    async def scenario():
        await ask(printer, "upload", "restart.gcode", gcode(laps=6))
        async with logging_to_api(tmp_path, printer) as (api, config):
            async with bridge(config, printer):
                await ask(printer, "start_print", "restart.gcode")
                await until(lambda: api.prints)
            await asyncio.to_thread(printer.wait_until_idle)
            assert api.prints[1]["status"] == 2  # nobody told the API yet
            async with bridge(config, printer):
                await until(lambda: api.prints[1]["status"] != 2)
                await asyncio.sleep(1)  # room for a duplicate, if there were one
            [job] = [j for j in await ask(printer, "jobs") if j["filename"] == "restart.gcode"]
            return api, job

    api, job = asyncio.run(scenario())

    assert len(api.prints) == 1
    assert len(api.completions) == 1
    assert api.prints[1]["status"] == 3
    [row] = api.prints[1]["filamentUsage"]
    assert row["lengthInM"] * 1000 == pytest.approx(job["filament_used"], rel=0.02)


def test_an_emergency_stop_is_logged_failed_with_a_note(tmp_path, own_printer):
    async def scenario():
        await ask(own_printer, "upload", "stopped.gcode", gcode(laps=20, speed=600))
        async with logging_to_api(tmp_path, own_printer) as (api, config):
            async with bridge(config, own_printer):
                await ask(own_printer, "start_print", "stopped.gcode")
                await until(lambda: api.prints)
                await ask(own_printer, "emergency_stop")
                await until(lambda: api.prints[1]["notes"])
            return api.prints[1]

    stopped = asyncio.run(scenario())

    assert stopped["status"] == 5  # Failed
    assert stopped["notes"] == "Klipper shutdown"


def test_the_fakes_history_entries_have_the_real_fields(tmp_path, printer):
    """tests/fake_moonraker.py builds history entries by hand; they must look like these."""

    async def scenario():
        await ask(printer, "upload", "fields.gcode", gcode(laps=1))
        await ask(printer, "start_print", "fields.gcode")
        await asyncio.to_thread(printer.wait_until_idle)
        fake = FakeMoonraker()
        await fake.finish_job(await fake.start_job("fields.gcode", notify=False), notify=False)
        [real] = [j for j in await ask(printer, "jobs") if j["filename"] == "fields.gcode"]
        return set(fake.jobs[0]), real

    fake_fields, real = asyncio.run(scenario())

    assert fake_fields <= set(real), fake_fields - set(real)
    assert isinstance(real["job_id"], str)
    assert {"estimated_time", "filament_total", "filament_weight_total"} <= set(real["metadata"])
