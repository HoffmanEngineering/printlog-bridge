"""Reading a `.bgcode` file's metadata, thumbnails and settings (libbgcode's specification),
from bytes fed in pieces as a download delivers them, and stopping at the G-code."""

from __future__ import annotations

import struct
from pathlib import Path

import pytest
from fake_prusalink import PNG, heatshrink_encode, make_bgcode

from printlog_bridge.adapters.prusalink.bgcode import (
    BgcodeReader,
    NotBgcode,
    heatshrink_decode,
    parse_ini,
)


def read(data: bytes, piece: int = 7) -> BgcodeReader:
    reader = BgcodeReader()
    for n in range(0, len(data), piece):
        if reader.feed(data[n : n + piece]):
            break
    return reader


class TestBlocks:
    def test_reads_every_metadata_block_and_the_thumbnail_and_stops_at_the_gcode(self):
        reader = read(make_bgcode())

        info = reader.info
        assert info.complete
        assert info.metadata["file"] == {"Producer": "PrusaSlicer 2.9.2"}
        assert info.metadata["printer"]["printer_model"] == "MK4S"
        assert info.metadata["print"]["filament used [g]"] == "12.34"
        assert info.metadata["slicer"]["printhost_apikey"] == "SECRET-KEY"
        assert [(t.format, t.width, t.height, t.data) for t in info.thumbnails] == [
            (0, 313, 173, PNG)
        ]
        assert info.problems == []

    def test_the_gcode_is_never_kept(self):
        data = make_bgcode()
        reader = BgcodeReader()
        reader.feed(data)

        assert reader.done
        assert b"SECRET-GCODE" not in repr(reader.info).encode()
        assert len(reader._buffer) == 0

    def test_says_when_it_is_done_before_the_rest_of_the_file(self):
        data = make_bgcode()
        gcode_header_end = data.index(b"SECRET-GCODE") - 2  # its parameters aren't needed

        assert BgcodeReader().feed(data[:gcode_header_end]) is True

    def test_a_file_without_checksums(self):
        info = read(make_bgcode(checksum=False)).info
        assert info.complete and info.metadata["print"]["filament used [g]"] == "12.34"

    @pytest.mark.parametrize("compression", [0, 1, 2, 3])
    def test_each_compression_of_every_block(self, compression):
        blocks = ("file", "printer", "print", "slicer", "thumbnail")
        data = make_bgcode(compression={b: compression for b in blocks})

        info = read(data, piece=64).info

        assert info.problems == []
        assert info.metadata["slicer"]["layer_height"] == "0.2"
        assert info.thumbnails[0].data == PNG

    def test_an_unknown_compression_is_skipped_and_said(self):
        data = bytearray(make_bgcode(checksum=False, thumbnails=()))
        # The printer block follows the file header and the file block.
        file_block = 8 + 2 + len(b"Producer=PrusaSlicer 2.9.2\n")
        at = 10 + file_block
        assert struct.unpack_from("<H", data, at)[0] == 3
        stored = struct.unpack_from("<I", data, at + 4)[0]
        data[at : at + 8] = struct.pack("<HHII", 3, 9, stored, stored)[:8]
        data[at + 8 : at + 8] = struct.pack("<I", stored)

        info = read(bytes(data)).info

        assert info.complete
        assert "printer" not in info.metadata
        assert any("compression 9" in p for p in info.problems)

    def test_not_a_bgcode_file(self):
        with pytest.raises(NotBgcode):
            BgcodeReader().feed(b"; generated by PrusaSlicer\n")
        with pytest.raises(NotBgcode):
            BgcodeReader().feed(b"; g")


class TestHeatshrink:
    @pytest.mark.parametrize("window", [11, 12])
    def test_round_trip_with_back_references(self, window):
        text = b"filament used [g]=1.00\nfilament used [mm]=2.00\n" * 30
        packed = heatshrink_encode(text, window, 4)

        assert len(packed) < len(text) // 2  # it did use back references
        assert heatshrink_decode(packed, window, 4, len(text)) == text

    def test_a_reference_before_the_start_is_refused(self):
        with pytest.raises(ValueError):
            heatshrink_decode(bytes([0b00000000, 0b00010000]), 11, 4, 10)


def test_ini_keys_keep_their_spaces_and_values_their_equals_signs():
    pairs = parse_ini(b"filament used [g] = 1.5, 2.5\nstart_gcode=M104 S=1\n; layer_height = 0.2\n")
    assert pairs == {
        "filament used [g]": "1.5, 2.5",
        "start_gcode": "M104 S=1",
        "layer_height": "0.2",
    }


FIXTURES = Path(__file__).parent / "fixtures" / "gcode"


class TestRealFiles:
    """Files PrusaSlicer 2.9.2 wrote (a 20 mm cube, sliced with its command line): the print
    and slicer metadata deflated, the G-code in Heatshrink 12/4 with MeatPack."""

    def test_an_mk4s_file(self):
        data = (FIXTURES / "prusaslicer-2.9.2-mk4s-cube.bgcode").read_bytes()
        reader = BgcodeReader()

        assert reader.feed(data)
        info = reader.info
        assert info.problems == []
        assert info.metadata["file"]["Producer"] == "PrusaSlicer 2.9.2"
        assert info.metadata["printer"]["printer_model"] == "MK4S"
        assert info.metadata["print"]["filament used [g]"] == "4.46"
        assert info.metadata["print"]["estimated printing time (normal mode)"] == "13m 54s"
        assert info.metadata["slicer"]["layer_height"] == "0.3"

    def test_an_xl_file_with_two_tools_has_a_value_per_tool(self):
        data = (FIXTURES / "prusaslicer-2.9.2-xl-two-tool-cube.bgcode").read_bytes()
        reader = BgcodeReader()

        assert reader.feed(data)
        meta = reader.info.metadata
        assert meta["printer"]["printer_model"] == "XL2"
        assert meta["print"]["filament used [g]"] == "2.19, 2.32"
        assert meta["print"]["filament used [mm]"] == "734.45, 759.54"
