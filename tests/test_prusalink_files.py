"""A PrusaLink job's file: the slicer's estimates per tool, the thumbnail and the settings, read
from the printer's metadata when it gives it, else from the file, stopping at its G-code."""

from __future__ import annotations

import asyncio
import contextlib
from pathlib import Path

import pytest
from fake_prusalink import PASSWORD, PNG, FakePrusaLink, make_bgcode, make_gcode

from printlog_bridge.adapters.prusalink.client import PrusaLinkClient
from printlog_bridge.adapters.prusalink.files import (
    PrusaLinkFiles,
    duration_of,
    facts_from_meta,
)
from printlog_bridge.core.status import NullReport

XL_PRINTER = {
    "printer_model": "XL5",
    "filament_type": "PLA;PETG;PLA;PLA;PLA",
    "nozzle_diameter": "0.4,0.4,0.4,0.4,0.4",
    "filament used [g]": "10.00, 0.00, 2.50, 0.00, 1.25",
    "filament used [mm]": "3300.0, 0.0, 800.0, 0.0, 400.0",
    "estimated printing time (normal mode)": "1d 2h 3m 4s",
}


class TestFacts:
    def test_one_tool(self):
        facts = facts_from_meta({"filament used [g]": "12.34", "filament used [mm]": "4130.20"})
        assert facts.grams == {0: 12.34}
        assert facts.mm == {0: 4130.2}

    def test_each_tool_of_an_xl_is_its_slot_and_unused_tools_are_left_out(self):
        facts = facts_from_meta(XL_PRINTER)

        assert facts.grams == {0: 10.0, 2: 2.5, 4: 1.25}
        assert facts.mm == {0: 3300.0, 2: 800.0, 4: 400.0}
        assert facts.duration_s == 93784
        assert facts.printer_model == "XL5"

    def test_pi_prusalink_meta_with_lists_per_tool(self):
        facts = facts_from_meta(
            {
                "filament used [g]": 13.0,
                "filament used [g] per tool": [10.0, 3.0],
                "filament used [mm] per tool": [3000.0, 900.0],
                "estimated_print_time": 600,
                "printer_model": "MK3S",
            }
        )

        assert facts.grams == {0: 10.0, 1: 3.0}
        assert facts.mm == {0: 3000.0, 1: 900.0}
        assert facts.duration_s == 600

    @pytest.mark.parametrize(
        ("text", "seconds"),
        [("42m 42s", 2562), ("1h 2m 3s", 3723), ("2d 0h 1m 0s", 172860), ("soon", None)],
    )
    def test_durations(self, text, seconds):
        assert duration_of(text) == seconds


@contextlib.asynccontextmanager
async def files_on_a_printer(**options):
    fake = FakePrusaLink()
    address = await fake.start()
    client = PrusaLinkClient(f"http://{address}", password=PASSWORD)
    try:
        yield fake, PrusaLinkFiles("mk4s", client, NullReport(), **options)
    finally:
        await client.close()
        await fake.close()


def job_of(fake: FakePrusaLink) -> dict:
    """`/api/v1/job` as the fake answers it."""
    return {
        "id": fake.job["id"],  # type: ignore[index]
        "file": {
            "display_name": fake.job["display_name"],  # type: ignore[index]
            "refs": {
                "download": fake.job["path"],  # type: ignore[index]
                "thumbnail": f"/thumb/l{fake.job['path']}",  # type: ignore[index]
            },
            "size": len(fake.files[fake.job["display_name"]]),  # type: ignore[index]
        },
    }


class TestRead:
    def test_a_bgcode_file_is_read_up_to_its_gcode(self):
        data = make_bgcode(gcode=b"G1 X1\n" * 400_000)

        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(7, "BENCHY.BGC", data)
                found = await files.read(job_of(fake))
                await asyncio.sleep(0.1)
                return found, fake.downloaded_bytes

        found, sent = asyncio.run(scenario())

        assert found.grams == {0: 12.34}
        assert found.duration_s == 3723
        assert found.printer_model == "MK4S"
        assert found.thumbnail == PNG
        assert found.metadata.slicer == "PrusaSlicer"
        assert found.metadata.slicer_version == "2.9.2"
        assert "; layer_height = 0.2" in found.settings.config_block
        assert "SECRET-GCODE" not in found.settings.config_block
        assert sent < len(data) // 2  # it stopped at the G-code

    def test_a_plain_gcode_file_is_read_for_its_tail(self):
        data = make_gcode(grams="5.5", size=1_000_000)

        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(8, "CUBE.GCO", data)
                fake.thumbnails["CUBE.GCO"] = PNG
                return await files.read(job_of(fake))

        found = asyncio.run(scenario())

        assert found.grams == {0: 5.5}
        assert found.thumbnail == PNG  # from the printer, not the file
        assert found.settings.header.startswith("; generated by PrusaSlicer 2.9.2")
        assert "; printer_model = MINI" in found.settings.config_block
        assert "SECRET-GCODE" not in found.settings.config_block

    def test_a_plain_gcode_file_over_the_cap_is_not_downloaded(self):
        async def scenario():
            async with files_on_a_printer(max_gcode_bytes=100_000) as (fake, files):
                fake.print_file(8, "CUBE.GCO", make_gcode(size=200_000))
                return await files.read(job_of(fake)), fake.downloads

        found, downloads = asyncio.run(scenario())

        assert downloads == []
        assert found.grams == {}

    def test_the_printers_meta_spares_the_download(self):
        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(9, "PART.GCO", make_gcode())
                job = job_of(fake)
                job["file"]["meta"] = {"filament used [g]": 3.0, "estimated_print_time": 60}
                return await files.read(job), fake.downloads

        found, downloads = asyncio.run(scenario())

        assert found.grams == {0: 3.0}
        assert downloads == []

    def test_read_once_per_job(self):
        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(7, "BENCHY.BGC", make_bgcode())
                await files.read(job_of(fake))
                await files.read(job_of(fake))
                return fake.downloads

        assert asyncio.run(scenario()) == ["BENCHY.BGC"]

    def test_a_missing_file_is_nothing_read(self):
        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(7, "BENCHY.BGC", make_bgcode())
                job = job_of(fake)
                del fake.files["BENCHY.BGC"]
                return await files.read(job)

        found = asyncio.run(scenario())
        assert found.grams == {} and found.settings is None

    def test_off_reads_nothing(self):
        async def scenario():
            async with files_on_a_printer(enabled=False) as (fake, files):
                fake.print_file(7, "BENCHY.BGC", make_bgcode())
                return await files.read(job_of(fake)), fake.requests

        found, requests = asyncio.run(scenario())
        assert found.grams == {} and requests == []


FIXTURES = Path(__file__).parent / "fixtures" / "gcode"


class TestRealFiles:
    def test_an_xl_file_from_prusaslicer_gives_each_tool_its_grams(self):
        data = (FIXTURES / "prusaslicer-2.9.2-xl-two-tool-cube.bgcode").read_bytes()

        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(4, "CUBE~1.BGC", data)
                return await files.read(job_of(fake))

        found = asyncio.run(scenario())

        assert found.grams == {0: 2.19, 1: 2.32}
        assert found.mm == {0: 734.45, 1: 759.54}
        assert found.duration_s == 842
        assert found.printer_model == "XL2"
        assert found.metadata.slicer_version == "2.9.2"
        assert found.metadata.filament_type == "PLA"
        assert "; perimeter_extruder = 1\n" in found.settings.config_block

    def test_a_plain_gcode_file_from_prusaslicer(self):
        data = (FIXTURES / "prusaslicer-2.9.2-calibration-cube.gcode").read_bytes()

        async def scenario():
            async with files_on_a_printer() as (fake, files):
                fake.print_file(4, "CUBE.GCO", data)
                return await files.read(job_of(fake))

        found = asyncio.run(scenario())

        assert found.mm == {0: 1332.37}
        assert found.settings.header.startswith("; generated by PrusaSlicer 2.9.2")
