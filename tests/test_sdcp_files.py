"""What the SDCP adapter reads of a job's file: the first part of its download, for the slicer's
header (Elegoo Slicer and OrcaSlicer write the estimates there) and its thumbnail. The download
is reported by one community note, not by Elegoo (#94), so every failure is a job logged
without usage, never an error."""

from __future__ import annotations

import asyncio
import base64
import contextlib

import bridge_helpers as helpers
from fake_elegoo import FakeElegoo
from fake_moonraker import eventually
from fake_printlog_api import FakePrintLogApi

from printlog_bridge.adapters.sdcp import SdcpAdapter
from printlog_bridge.adapters.sdcp.files import HEAD_BYTES, SdcpFiles, download_path, facts_from

PNG = b"\x89PNG\r\n\x1a\n" + b"\x00" * 40


def thumbnail_block(width: int, height: int, data: bytes) -> str:
    encoded = base64.b64encode(data).decode()
    return f"; thumbnail begin {width}x{height} {len(encoded)}\n; {encoded}\n; thumbnail end\n"


def orca_gcode(
    weight: str = "12.34", length: str = "4130.20", time: str = "1h 2m 3s", body: int = 0
) -> bytes:
    header = (
        "; HEADER_BLOCK_START\n"
        "; generated by ElegooSlicer 1.1.5 on 2026-10-20 at 10:00:00\n"
        "; total layer number: 200\n"
        f"; total filament length [mm] : {length}\n"
        "; total filament volume [cm^3] : 9935.70\n"
        f"; total filament weight [g] : {weight}\n"
        f"; model printing time: 58m 1s; total estimated time: {time}\n"
        "; HEADER_BLOCK_END\n\n"
        "; THUMBNAIL_BLOCK_START\n" + thumbnail_block(300, 300, PNG) + "; THUMBNAIL_BLOCK_END\n\n"
    )
    return header.encode() + b"G1 X1 Y1 E0.1\n" * body


class TestHeader:
    def test_reads_the_estimates_from_an_orca_header(self):
        found = facts_from(orca_gcode())
        assert found.grams == {0: 12.34}
        assert found.mm == {0: 4130.2}
        assert found.duration_s == 3723
        assert found.thumbnail == PNG
        assert found.settings is not None and "ElegooSlicer" in found.settings.header
        assert found.metadata is not None and found.metadata.slicer == "ElegooSlicer"

    def test_a_value_per_tool(self):
        found = facts_from(orca_gcode(weight="10.00, 0.00, 2.50", length="3000.0,0,800"))
        assert found.grams == {0: 10.0, 2: 2.5}
        assert found.mm == {0: 3000.0, 2: 800.0}

    def test_prusaslicer_style_lines_too(self):
        data = b"; generated by PrusaSlicer 2.9.2\n; filament used [g] = 7.5\nG28\n"
        assert facts_from(data).grams == {0: 7.5}

    def test_nothing_from_anything_else(self):
        for data in (b"", b"\xff\xd8binary", b"G28\nG1 X1\n", b"; nothing here\nG28\n"):
            found = facts_from(data)
            assert (found.grams, found.mm, found.duration_s) == ({}, {}, None)


class TestDownloadPath:
    def test_a_full_path_and_a_bare_name(self):
        assert download_path("/local/Benchy.gcode") == "/downloadFile/local/Benchy.gcode"
        assert download_path("Benchy.gcode") == "/downloadFile/local/Benchy.gcode"
        quoted = "/downloadFile/local/A%20cube%20%232.gcode"
        assert download_path("/local/A cube #2.gcode") == quoted

    def test_never_leaves_the_printers_storage(self):
        assert download_path("../../etc/passwd") is None
        assert download_path("/local/../x.gcode") is None
        assert download_path("") is None


@contextlib.asynccontextmanager
async def printer():
    fake = FakeElegoo()
    await fake.start()
    try:
        yield fake
    finally:
        await fake.close()


def reader(fake: FakeElegoo, **kwargs) -> SdcpFiles:
    return SdcpFiles("cc", fake.host, fake.port, **kwargs)


class TestReader:
    def test_reads_only_the_start_of_the_file(self):
        async def scenario():
            async with printer() as fake:
                fake.files["/local/Benchy.gcode"] = orca_gcode(body=40_000)
                found = await reader(fake).read("/local/Benchy.gcode")
                return found, fake.downloads

        found, downloads = asyncio.run(scenario())
        assert found.grams == {0: 12.34} and found.thumbnail == PNG
        assert downloads == [("/local/Benchy.gcode", f"bytes=0-{HEAD_BYTES - 1}")]

    def test_a_printer_that_ignores_the_range_is_read_no_further(self):
        async def scenario():
            async with printer() as fake:
                fake.honor_range = False
                fake.files["/local/Benchy.gcode"] = orca_gcode(body=100_000)
                return await reader(fake).read("/local/Benchy.gcode")

        assert asyncio.run(scenario()).grams == {0: 12.34}

    def test_asks_for_the_file_uncompressed_and_never_inflates_one(self):
        """A compressed answer would grow past the cap when inflated: it is read as it came,
        no further than the cap, and gives nothing."""

        async def scenario():
            async with printer() as fake:
                fake.gzip, fake.honor_range = True, False
                fake.files["/local/Benchy.gcode"] = orca_gcode() + b"G1 X1\n" * 2_000_000
                found = await reader(fake).read("/local/Benchy.gcode")
                return found, fake.download_encodings

        found, encodings = asyncio.run(scenario())
        assert encodings == ["identity"]
        assert found.grams == {}

    def test_a_missing_file_or_no_web_server_is_no_usage(self):
        async def scenario():
            async with printer() as fake:
                missing = await reader(fake).read("/local/Gone.gcode")
                closed = SdcpFiles("cc", fake.host, 9)
                return missing, await closed.read("/local/Gone.gcode")

        for found in asyncio.run(scenario()):
            assert (found.grams, found.mm, found.thumbnail) == ({}, {}, None)

    def test_off_reads_nothing(self):
        async def scenario():
            async with printer() as fake:
                fake.files["/local/Benchy.gcode"] = orca_gcode()
                found = await reader(fake, enabled=False).read("/local/Benchy.gcode")
                return found, fake.downloads

        found, downloads = asyncio.run(scenario())
        assert found.grams == {} and downloads == []


class TestConfig:
    def test_the_web_port_and_turning_it_off(self):
        adapter = SdcpAdapter.from_config("cc", {"host": "192.168.1.77"})
        assert (adapter.http_port, adapter.files) == (80, True)
        adapter = SdcpAdapter.from_config(
            "cc", {"host": "192.168.1.77", "http_port": "8080", "files": "false"}
        )
        assert (adapter.http_port, adapter.files) == (8080, False)


def test_the_bridge_sends_the_slicers_estimate_marked_estimated(tmp_path):
    async def scenario():
        api = FakePrintLogApi()
        api_url = await api.start()
        try:
            async with printer() as fake:
                fake.files["/local/Benchy.gcode"] = orca_gcode()
                config = tmp_path / "printlog-bridge.cfg"
                config.write_text(
                    f"[bridge]\napi_url = {api_url}\napi_key = key-123\n"
                    f"state_dir = {tmp_path / 'state'}\n"
                    f"[printer cc]\nadapter = sdcp\nprinter_id = 42\nhost = {fake.host}\n"
                    f"port = {fake.port}\nhttp_port = {fake.port}\n",
                    encoding="utf-8",
                )
                async with helpers.bridge(
                    config, connected=lambda: fake.sockets, disconnected=lambda: True
                ):
                    await fake.print_file("/local/Benchy.gcode")
                    await eventually(lambda: api.prints, timeout=10)
                    await fake.complete()
                    await eventually(lambda: api.prints[1]["status"] != 2, timeout=10)
                return api.prints[1], fake.refused
        finally:
            await api.close()

    done, refused = asyncio.run(scenario())
    assert done["status"] == 3
    [row] = done["filamentUsage"]
    assert (row["slot"], row["amountMg"], row["actualIsEstimate"]) == (0, 12340, True)
    assert refused == []
