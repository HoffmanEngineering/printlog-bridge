"""Sending a print's slicer settings (#36): once per job, through the outbox, after the print
exists, and never in the way of logging the print itself."""

from __future__ import annotations

import asyncio
import logging

from fake_printlog_api import FakePrintLogApi
from test_job_logger import drain, finished, logging_to, run, started

from printlog_bridge.core.config import Adoption
from printlog_bridge.core.events import JobSlicerSettings, SlicerFile, SlicerMetadata
from printlog_bridge.core.lifecycle import IMAGE_MAX_ATTEMPTS
from printlog_bridge.core.state import PrinterState

METADATA = SlicerMetadata(slicer="OrcaSlicer", slicer_version="2.2.0", layer_height_mm=0.2)
HEADER = "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.2.0\n; HEADER_BLOCK_END"
BLOCK = "; CONFIG_BLOCK_START\n; layer_height = 0.2\n; printhost_apikey = SECRET-1\n"
FILE = SlicerFile(header=HEADER, config_block=BLOCK)
SCRUBBED = "; CONFIG_BLOCK_START\n; layer_height = 0.2\n; printhost_apikey =\n"


def settings(
    file: SlicerFile | None = FILE,
    *,
    metadata: SlicerMetadata | None = METADATA,
    reads: list | None = None,
    error: Exception | None = None,
    hang: bool = False,
    job_id: str = "00000A",
) -> JobSlicerSettings:
    async def read() -> SlicerFile | None:
        if reads is not None:
            reads.append(job_id)
        if hang:
            await asyncio.Event().wait()
        if error is not None:
            raise error
        return file

    return JobSlicerSettings("voron", job_id, metadata, read)


def posted_paths(api: FakePrintLogApi) -> list[str]:
    return [f"{method} {path}" for method, path in api.requests if method != "GET"]


class TestSent:
    def test_once_the_print_exists_scrubbed_and_before_its_end(self, tmp_path):
        api = FakePrintLogApi()

        run(api, tmp_path, started(), settings(), finished())

        [(print_id, body)] = api.slicer_posts
        assert body == {
            "header": HEADER,
            "configBlock": SCRUBBED,
            "metadata": {"slicer": "OrcaSlicer", "slicerVersion": "2.2.0", "layerHeightMm": 0.2},
        }
        assert api.prints[print_id]["slicer"] == "orcaslicer"
        assert posted_paths(api) == [
            "POST /api/Prints",
            f"POST /api/Prints/{print_id}/slicer-settings",
            f"POST /api/Prints/{print_id}/complete",
        ]
        assert api.prints[print_id]["status"] == 3

    def test_read_and_sent_once_however_often_the_job_is_replayed(self, tmp_path):
        api = FakePrintLogApi()
        reads: list = []

        run(api, tmp_path, started(), settings(reads=reads), settings(reads=reads))
        run(api, tmp_path, started(), settings(reads=reads), finished())  # after a restart

        assert reads == ["00000A"]
        assert len(api.slicer_posts) == 1

    def test_a_job_logged_before_isnt_read(self, tmp_path):
        api = FakePrintLogApi()
        reads: list = []

        run(api, tmp_path, started(), finished())
        run(api, tmp_path, started(), settings(reads=reads), finished())  # history replayed

        assert reads == []
        assert api.slicer_posts == []

    def test_survives_a_restart_while_the_api_is_down(self, tmp_path):
        api = FakePrintLogApi()
        api.offline = True
        run(api, tmp_path, started(), settings(), timeout=0.2)
        assert api.slicer_posts == []

        api.offline = False
        run(api, tmp_path)

        [(_, body)] = api.slicer_posts
        assert body["configBlock"] == SCRUBBED

    def test_metadata_alone_when_the_file_cant_be_read(self, tmp_path):
        api = FakePrintLogApi()

        run(api, tmp_path, started(), settings(error=OSError("gone")), finished())

        [(_, body)] = api.slicer_posts
        assert body == {"metadata": {"slicer": "OrcaSlicer", "slicerVersion": "2.2.0",
                                     "layerHeightMm": 0.2}}  # fmt: skip
        assert api.prints[1]["status"] == 3

    def test_metadata_alone_when_reading_takes_too_long(self, tmp_path):
        api = FakePrintLogApi()

        run(api, tmp_path, started(), settings(hang=True), finished(), image_timeout=0.1)

        [(_, body)] = api.slicer_posts
        assert set(body) == {"metadata"}
        assert api.prints[1]["status"] == 3

    def test_nothing_when_theres_nothing_to_record(self, tmp_path):
        api = FakePrintLogApi()

        run(api, tmp_path, started(), settings(None, metadata=None), finished())

        assert api.slicer_posts == []
        assert api.prints[1]["status"] == 3

    def test_to_the_print_adopted_for_the_job(self, tmp_path):
        api = FakePrintLogApi()
        print_id = api.user_creates("Benchy", file_name="shelf_bracket_0.2mm_PLA_MK4_1h2m.gcode")

        run(api, tmp_path, started(), settings(), finished())

        assert [p for p, _ in api.slicer_posts] == [print_id]


class TestOff:
    def test_the_file_is_never_read_and_nothing_sent(self, tmp_path):
        api = FakePrintLogApi()
        reads: list = []

        run(api, tmp_path, started(), settings(reads=reads), finished(), slicer_settings=False)

        assert reads == []
        assert api.slicer_posts == []
        assert api.prints[1]["status"] == 3


class TestAnswers:
    def test_a_print_with_a_plugins_settings_is_skipped_up_front(self, tmp_path):
        """The lookup says `hasSlicerSettings`: the uploader's record is the richer one."""
        api = FakePrintLogApi()
        api.user_creates("Benchy", file_name="shelf_bracket_0.2mm_PLA_MK4_1h2m.gcode",
                         slicer="orcaslicer")  # fmt: skip

        run(api, tmp_path, started(), settings(), finished())

        assert api.slicer_posts == []
        assert api.prints[1]["status"] == 3

    def test_409_is_done_and_not_retried(self, tmp_path):
        api = FakePrintLogApi()
        api.slicer_settings_status = 409

        run(api, tmp_path, started(), settings(), finished())

        assert len(api.slicer_posts) == 1
        assert api.prints[1]["status"] == 3

    def test_the_lookup_missing_the_flag_still_ends_in_a_409(self, tmp_path):
        """A print given the uploader's settings after the lookup: the API refuses, once."""
        api = FakePrintLogApi()

        def uploader_records(api):
            api.prints[1]["slicer"] = "orcaslicer"

        run(api, tmp_path, started(), uploader_records, settings(), finished())

        assert len(api.slicer_posts) == 1
        assert 1 not in api.slicer_records
        assert api.prints[1]["status"] == 3

    def test_400_and_413_are_logged_once_and_not_retried(self, tmp_path, caplog):
        for status in (400, 413):
            api = FakePrintLogApi()
            api.slicer_settings_status = status
            caplog.clear()

            with caplog.at_level(logging.WARNING):
                run(api, tmp_path / str(status), started(), settings(), finished())

            assert len(api.slicer_posts) == 1
            assert api.prints[1]["status"] == 3
            [warning] = [r for r in caplog.records if "slicer settings" in r.getMessage()]
            assert f"({status})" in warning.getMessage()
            assert "SECRET" not in caplog.text

    def test_404_drops_them(self, tmp_path):
        """The print is gone, or the API is older than the endpoint: either way, nothing to do."""
        api = FakePrintLogApi()
        api.slicer_settings_route = False

        run(api, tmp_path, started(), settings(), finished())

        assert ("POST", "/api/Prints/1/slicer-settings") in api.requests
        assert api.prints[1]["status"] == 3

    def test_an_api_without_the_endpoint_isnt_asked_again_this_run(self, tmp_path, caplog):
        api = FakePrintLogApi()
        api.slicer_settings_status = 405
        reads: list = []

        async def scenario():
            async with logging_to(api, tmp_path) as logger:
                for job in ("00000A", "00000B"):
                    await logger.emit(started(job))
                    await logger.emit(settings(reads=reads, job_id=job))
                    await drain(logger)
                    await logger.emit(finished(job))
                    await drain(logger)
                logger.close()

        with caplog.at_level(logging.WARNING):
            asyncio.run(scenario())

        assert len(api.slicer_posts) == 1
        assert reads == ["00000A"]
        assert [p["status"] for p in api.prints.values()] == [3, 3]
        assert len([r for r in caplog.records if "slicer settings" in r.getMessage()]) == 1

    def test_a_server_error_is_retried(self, tmp_path):
        api = FakePrintLogApi()

        def outage(api):
            api.fail_next(2, 503)

        run(api, tmp_path, started(), outage, settings(), finished())

        assert len(api.slicer_records) == 1
        assert api.prints[1]["status"] == 3

    def test_a_rate_limit_is_waited_out(self, tmp_path):
        api = FakePrintLogApi()

        def limited(api):
            api.fail_next(1, 429, {"Retry-After": "0"})

        run(api, tmp_path, started(), limited, settings(), finished())

        assert len(api.slicer_records) == 1

    def test_a_send_that_keeps_failing_never_holds_up_the_print(self, tmp_path):
        api = FakePrintLogApi()
        api.slicer_settings_status = 500

        run(api, tmp_path, started(), settings(), finished(), timeout=5.0)

        assert len(api.slicer_posts) == IMAGE_MAX_ATTEMPTS
        assert api.prints[1]["status"] == 3

    def test_no_print_no_send(self, tmp_path):
        """Finish-only mode with nothing to adopt: the job isn't logged, so neither are these."""
        api = FakePrintLogApi()

        run(
            api, tmp_path, started(), settings(), finished(),
            adoption=Adoption(adopt=True, create=False),
        )  # fmt: skip

        assert api.slicer_posts == []
        state = PrinterState.load(tmp_path, "voron")
        assert state.jobs["00000A"].finished
