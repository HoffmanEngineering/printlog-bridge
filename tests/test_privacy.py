class TestOnlyTheHeaderAndSettingsAreRead:
    """Of a G-code file only its header and its settings block are read, by byte range, and
    nothing at all with `slicer_settings = false`. A thumbnail entry pointing at anything but an
    image is skipped before it is read."""

    THUMBNAIL_JOB = {
        "filename": "benchy.gcode",
        "metadata": {"thumbnails": [{"relative_path": "benchy.gcode"}]},
    }

    def test_with_slicer_settings_off_the_gcode_file_is_never_asked_for(self, tmp_path):
        result = asyncio.run(one_print(tmp_path, slicer_settings=False))

        assert result["moonraker"].downloads == [".thumbs/benchy-300x300.png"]
        assert result["moonraker"].ranges == [(".thumbs/benchy-300x300.png", None)]
        assert result["api"].slicer_posts == []
        assert result["api"].heartbeats
        assert all(body["slicerSettings"] is False for _, body in result["api"].heartbeats)

    def test_local_reads_only_the_two_ranges(self, tmp_path, monkeypatch):
        from printlog_bridge.adapters.moonraker import slicer
        from printlog_bridge.adapters.moonraker.slicer import MoonrakerSlicerFiles

        (tmp_path / "benchy.gcode").write_bytes(GCODE)
        spans = []
        original = slicer.read_range

        async def recording(path, start, end, expected_size):
            spans.append((start, end))
            return await original(path, start, end, expected_size)

        monkeypatch.setattr(slicer, "read_range", recording)

        async def calls(method, params=None):
            assert method == "server.files.roots", "nothing else should be asked"
            return [{"name": "gcodes", "path": str(tmp_path)}]

        reader = MoonrakerSlicerFiles(
            "voron", MoonrakerImages("voron", url=None, socket=tmp_path / "moonraker.sock")
        )
        job = {"filename": "benchy.gcode", "metadata": METADATA}
        read = asyncio.run(reader.read(calls, job))

        assert spans == [
            (0, METADATA["gcode_start_byte"]),
            (METADATA["gcode_end_byte"] - 1, METADATA["size"]),
        ]
        assert "SECRET-GCODE" not in read.header + read.config_block

    def test_a_thumbnail_pointing_at_the_gcode_is_never_read_remote(self):
        async def scenario():
            fake = FakeMoonraker()
            fake.files["benchy.gcode"] = GCODE
            url = await fake.start()
            try:
                images = MoonrakerImages("voron", url=url, socket=None)
                return await images.thumbnail(_no_calls, self.THUMBNAIL_JOB), fake.downloads
            finally:
                await fake.close()

        thumbnail, downloads = asyncio.run(scenario())

        assert thumbnail is None
        assert downloads == []

    def test_a_thumbnail_pointing_at_the_gcode_is_never_read_local(self, tmp_path):
        (tmp_path / "benchy.gcode").write_bytes(GCODE)

        async def calls(method, params=None):
            assert method == "server.files.roots", "nothing else should be asked"
            return [{"name": "gcodes", "path": str(tmp_path)}]

        images = MoonrakerImages("voron", url=None, socket=tmp_path / "moonraker.sock")
        assert asyncio.run(images.thumbnail(calls, self.THUMBNAIL_JOB)) is None


