def with_password(url: str, user: str = "maker") -> str:
    return url.replace("http://", f"http://{user}:{PASSWORD}@", 1)


class BridgeLogs(logging.Handler):
    """Everything the bridge itself logs (the fake servers' access logs aren't the bridge's)."""

    def __init__(self) -> None:
        super().__init__(logging.DEBUG)
        self.lines: list[str] = []

    def emit(self, record: logging.LogRecord) -> None:
        self.lines.append(logging.Formatter().format(record))

    @property
    def text(self) -> str:
        return "\n".join(self.lines)


@contextlib.contextmanager
def bridge_logs():
    logs = BridgeLogs()
    logger = logging.getLogger("printlog_bridge")
    level = logger.level
    logger.addHandler(logs)
    logger.setLevel(logging.DEBUG)
    try:
        yield logs
    finally:
        logger.removeHandler(logs)
        logger.setLevel(level)


def state_files(state: Path) -> dict[str, str]:
    """Every file the bridge wrote, except the key file the user gave it."""
    return {
        path.relative_to(state).as_posix(): path.read_bytes().decode("utf-8", errors="replace")
        for path in state.rglob("*")
        if path.is_file() and path.name != "api_key"
    }


@contextlib.contextmanager
def recording_connections(monkeypatch):
    """Every host and port the bridge makes an HTTP or WebSocket request to."""
    contacted: list[tuple[str, int]] = []
    original = aiohttp.ClientSession._request

    async def recording(self, method, str_or_url, *args, **kwargs):
        url = yarl.URL(str(str_or_url))
        contacted.append((url.host, url.port))
        return await original(self, method, str_or_url, *args, **kwargs)

    monkeypatch.setattr(aiohttp.ClientSession, "_request", recording)
    yield contacted


async def one_print(
    tmp_path: Path,
    *,
    snapshots: bool = True,
    webcam_status: int = 200,
    slicer_settings: bool = True,
    timelapse: bool = False,
):
    """A whole print, start to end, through the bridge in remote mode, with a Moonraker that
    needs a key, a URL with a password, and a webcam that needs a password and a token. With
    `timelapse`, moonraker-timelapse renders its video, and the account has Pro."""
    moonraker = FakeMoonraker(api_key=MOONRAKER_KEY, hostname=HOSTNAME, timelapse=timelapse)
    api = FakePrintLogApi(api_key=API_KEY)
    api.pro = timelapse
    cam = FakeWebcam(credentials=("cam", PASSWORD), status=webcam_status)
    moonraker_url, api_url, cam_url = await moonraker.start(), await api.start(), await cam.start()
    moonraker.files["benchy.gcode"] = GCODE
    moonraker.files[".thumbs/benchy-300x300.png"] = THUMBNAIL
    moonraker.webcams = [
        {
            "name": "cam",
            "enabled": True,
            "snapshot_url": f"{with_password(cam_url, 'cam')}/?action=snapshot&token="
            + WEBCAM_TOKEN,
            "stream_url": "",
        }
    ]
    state = tmp_path / "state"
    state.mkdir()
    (state / "api_key").write_text(API_KEY + "\n", encoding="utf-8")
    config_path = tmp_path / "printlog-bridge.cfg"
    config_path.write_text(
        # Traced, so the trace is checked for secrets with everything else the bridge writes.
        f"[bridge]\napi_url = {api_url}\nstate_dir = {state}\ntrace = true\n"
        f"[printer voron]\nprinter_id = 42\nurl = {with_password(moonraker_url)}\n"
        f"moonraker_api_key = {MOONRAKER_KEY}\nsnapshots = {'true' if snapshots else 'false'}\n"
        f"slicer_settings = {'true' if slicer_settings else 'false'}\n",
        encoding="utf-8",
    )
    try:
        async with helpers.bridge(
            config_path,
            connected=lambda: moonraker.client_count == 1,
            disconnected=lambda: moonraker.client_count == 0,
            heartbeat_interval=0.2,
        ):
            job = await moonraker.start_job("benchy.gcode", METADATA)
            await eventually(lambda: api.images, WAIT_S)
            if slicer_settings:
                await eventually(lambda: api.slicer_records, WAIT_S)
            await moonraker.finish_job(job)
            await eventually(lambda: api.prints[1]["status"] == 3, WAIT_S)
            if snapshots and webcam_status == 200:
                await eventually(lambda: len(api.images) == 2, WAIT_S)
            else:
                await asyncio.sleep(0.3)
            if timelapse:
                await moonraker.render_timelapse("benchy.gcode", MP4)
                await eventually(lambda: api.attachments.get(1), WAIT_S)
            # Moonraker restarts: the reason is logged and kept for `status`.
            await moonraker.drop()
            await eventually(lambda: moonraker.client_count == 1, WAIT_S)
            # A heartbeat fails, and says why in the log; the next one reports it, scrubbed.
            api.fail_next(1)
            await eventually(lambda: api.heartbeats[-1][1]["errorCount"] > 0, WAIT_S)
    finally:
        await moonraker.close()
        await api.close()
        await cam.close()
    config = load_config(config_path, adapters=ADAPTERS, env={}, home=tmp_path)
    return {
        "moonraker": moonraker,
        "api": api,
        "cam": cam,
        "state": state,
        "config": config,
        "ports": {
            "moonraker": yarl.URL(moonraker_url).port,
            "api": yarl.URL(api_url).port,
            "webcam": yarl.URL(cam_url).port,
            "storage": api.store_port,
        },
    }


@pytest.fixture(scope="module")
def run(tmp_path_factory):
    """One print for every test in TestWhatIsSent: it takes a few seconds."""
    with contextlib.ExitStack() as stack:  # not one `with (...)`: Python 3.9
        monkeypatch = stack.enter_context(pytest.MonkeyPatch.context())
        logs = stack.enter_context(bridge_logs())
        contacted = stack.enter_context(recording_connections(monkeypatch))
        result = asyncio.run(one_print(tmp_path_factory.mktemp("print")))
    result["contacted"] = contacted
    result["logs"] = logs.text
    return result


class TestWhatIsSent:
    def test_only_the_listed_calls_reach_3d_print_log(self, run):
        for method, path in run["api"].requests:
            assert any(method == m and re.fullmatch(pattern, path) for m, pattern in API_CALLS), (
                f"{method} {path} isn't in docs/privacy.md"
            )

    def test_a_print_is_created_and_completed_with_only_the_listed_fields(self, run):
        api = run["api"]
        assert api.created and api.completions
        for body in api.created:
            assert set(body) <= CREATE_FIELDS
        for body in api.completions:
            assert set(body) <= COMPLETE_FIELDS
        for body in [*api.created, *api.completions]:
            for row in body.get("filamentUsage", []):
                assert set(row) <= USAGE_FIELDS

    def test_every_heartbeat_carries_exactly_the_listed_fields(self, run):
        heartbeats = run["api"].heartbeats
        assert heartbeats
        for _, body in heartbeats:
            assert CONNECTION_FIELDS <= set(body) <= CONNECTION_FIELDS | SOFTWARE_FIELDS

    def test_each_heartbeat_field_holds_what_docs_privacy_md_says(self, run):
        [_, body] = run["api"].heartbeats[-1]
        assert body["kind"] == "moonraker"
        assert body["displayName"] == "printlog-bridge (voron)"
        assert body["agentVersion"] == __version__
        assert body["printerId"] == 42
        assert body["mode"] == "remote"
        assert body["firmwareName"] == "Klipper"
        assert body["firmwareVersion"] == "v0.12.0-fake"
        assert body["hostSoftwareName"] == "Moonraker"
        assert body["hostSoftwareVersion"] == "v0.9.3-fake"
        assert body["printerModel"] == "Voron 2.4"
        assert isinstance(body["outboxDepth"], int)
        assert body["outboxOldestAgeSeconds"] is None or body["outboxDepth"] > 0
        assert body["errorCount"] >= 1
        assert body["lastError"].startswith("couldn't send the heartbeat")
        assert datetime.fromisoformat(body["lastErrorAt"]).tzinfo is not None
        assert body["snapshots"] is True
        assert body["slicerSettings"] is True

    def test_no_heartbeat_holds_a_host_address_file_name_or_key(self, run):
        for _, body in run["api"].heartbeats:
            # The printer's name from the config is in displayName, as it always was.
            sent = json.dumps({k: v for k, v in body.items() if k != "displayName"})
            for leak in (*SECRETS, "127.0.0.1", "localhost", HOSTNAME, "benchy", ".gcode",
                         "voron", str(run["state"]), "http"):  # fmt: skip
                assert leak not in sent, (leak, body)

