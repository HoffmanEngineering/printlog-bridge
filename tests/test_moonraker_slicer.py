FIXTURES = Path(__file__).parent / "fixtures"
GCODE = FIXTURES / "gcode"
SECRET = "SECRET-from-the-slicer"


def fixture(name: str) -> bytes:
    """A real slicer's file, with a printer host and key in its settings, as many have."""
    data = (GCODE / name).read_bytes()
    marker = b"; layer_height = 0.2\n"
    assert data.count(marker) == 1
    secrets = f"; print_host = http://maker:{SECRET}@voron.local\n; printhost_apikey = {SECRET}\n"
    return data.replace(marker, marker + secrets.encode())


ORCA = fixture("orcaslicer-2.2.0-rc-calibration-cube.gcode")
PRUSA = fixture("prusaslicer-2.9.2-calibration-cube.gcode")


def job(name: str, data: bytes, **metadata) -> dict:
    return {
        "job_id": "00000A",
        "filename": name,
        "start_time": 1791167314.0,
        "status": "in_progress",
        "metadata": {**gcode_metadata(data), "slicer": "OrcaSlicer", **metadata},
    }


def ranges(fake: FakeMoonraker) -> list[tuple[int, int]]:
    """Each byte range asked for, `[first, last]` as in the header."""
    spans = []
    for _, header in fake.ranges:
        assert header is not None, "a G-code file is only ever read by range"
        first, last = header.removeprefix("bytes=").split("-")
        spans.append((int(first), int(last)))
    return spans


def assert_no_toolpaths(spans: list[tuple[int, int]], data: bytes) -> None:
    """No range reaches into the G-code, but for the line break that ends its last line, which
    the settings read starts on so that it can tell a whole first line from a cut one."""
    metadata = gcode_metadata(data)
    toolpaths = range(metadata["gcode_start_byte"], metadata["gcode_end_byte"] - 1)
    assert data[toolpaths.stop : toolpaths.stop + 1] == b"\n"
    for first, last in spans:
        assert last < toolpaths.start or first >= toolpaths.stop, (first, last)


async def no_calls(method, params=None):
    raise AssertionError(f"unexpected call {method}")


@contextlib.asynccontextmanager
async def moonraker(**options):
    fake = FakeMoonraker(**options)
    url = await fake.start()
    try:
        yield fake, url
    finally:
        await fake.close()


def remote(url: str, **options) -> MoonrakerSlicerFiles:
    return MoonrakerSlicerFiles("voron", MoonrakerImages("voron", url=url, socket=None, **options))


def read_remote(
    name: str,
    data: bytes,
    the_job: dict | None = None,
    call=no_calls,
    *,
    ignore_range: bool = False,
    **fake_opts,
):
    async def scenario():
        async with moonraker(**fake_opts) as (fake, url):
            fake.files[name] = data
            fake.ignore_range = ignore_range
            options = {"api_key": fake.api_key} if fake.api_key else {}
            read = await remote(url, **options).read(call, the_job or job(name, data))
            return read, fake

    return asyncio.run(scenario())


class TestRemote:
    @pytest.mark.parametrize(
        ("name", "data", "header_end", "first_line"),
        [
            ("cube.gcode", ORCA, 8045, "; HEADER_BLOCK_START"),
            ("parts/cube.gcode", PRUSA, 303, "; generated by PrusaSlicer 2.9.2"),
        ],
    )
    def test_reads_the_header_and_the_settings_block_only(self, name, data, header_end, first_line):
        read, fake = read_remote(name, data)

        end = gcode_metadata(data)["gcode_end_byte"]
        assert ranges(fake) == [(0, header_end - 1), (end - 1, len(data) - 1)]
        assert_no_toolpaths(ranges(fake), data)
        assert {path for path, _ in fake.ranges} == {name}
        assert read.header.startswith(first_line)
        assert read.config_block == data[end:].decode()
        assert "; layer_height = 0.2\n" in read.config_block

    def test_with_moonrakers_key(self):
        read, fake = read_remote("cube.gcode", ORCA, api_key="mrk")

        assert read is not None and read.config_block

    def test_a_settings_block_over_the_cap_is_read_to_the_cap_from_the_end(self):
        filler = b"".join(b"; setting_%06d = %0100d\n" % (n, n) for n in range(6000))
        data = ORCA + filler
        read, fake = read_remote("cube.gcode", data)

        [_, (first, last)] = ranges(fake)
        assert (first, last) == (len(data) - CONFIG_BLOCK_MAX_BYTES, len(data) - 1)
        assert read.config_block.startswith("; setting_")  # the cut line is dropped
        assert read.config_block.endswith(f"; setting_005999 = {5999:0100d}\n")

    def test_the_header_is_never_more_than_its_cap(self):
        data = b"; HEADER_BLOCK_START\n" + b"; " + b"x" * (2 * HEADER_MAX_BYTES) + b"\nG28\nG1 X1\n"
        read, fake = read_remote("cube.gcode", data)

        assert ranges(fake)[0] == (0, HEADER_MAX_BYTES - 1)
        assert read.header == "; HEADER_BLOCK_START"

    def test_without_where_the_gcode_ends_reads_a_bounded_tail_and_keeps_only_the_comments(
        self,
    ):
        """Moonraker gives no `gcode_end_byte` or `gcode_start_byte` for a file whose commands
        it couldn't find: the last 128 KB and the first 4 KB are read, and only what follows the
        last command is kept."""
        the_job = job("cube.gcode", ORCA)
        del the_job["metadata"]["gcode_end_byte"], the_job["metadata"]["gcode_start_byte"]

        read, fake = read_remote("cube.gcode", ORCA, the_job)

        size = len(ORCA)
        assert ranges(fake) == [
            (0, HEADER_FALLBACK_BYTES - 1),
            (max(0, size - TAIL_FALLBACK_BYTES), size - 1),
        ]
        assert read.config_block == ORCA[gcode_metadata(ORCA)["gcode_end_byte"] :].decode()
        assert read.header.endswith("; HEADER_BLOCK_END")

    def test_asks_moonraker_for_the_metadata_a_history_entry_lacks(self):
        asked = []

        async def call(method, params=None):
            asked.append((method, params))
            assert method == "server.files.metadata"
            return gcode_metadata(ORCA)

        the_job = job("cube.gcode", ORCA)
        the_job["metadata"] = {}
        read, _ = read_remote("cube.gcode", ORCA, the_job, call)

        assert asked == [("server.files.metadata", {"filename": "cube.gcode"})]
        assert read.config_block.startswith("; EXECUTABLE_BLOCK_END")

    def test_a_file_changed_since_the_job_started_isnt_read_as_its_settings(self):
        the_job = job("cube.gcode", ORCA)
        read, fake = read_remote("cube.gcode", PRUSA, the_job)  # replaced by another file

        assert read is None

    def test_a_server_that_ignores_the_range_is_given_up_on(self, monkeypatch):
        """It would send the whole file, toolpaths and all: not a byte of the body is read."""
        chunks = []
        original = aiohttp.StreamReader.iter_chunked

        def recording(self, n):
            chunks.append(n)
            return original(self, n)

        monkeypatch.setattr(aiohttp.StreamReader, "iter_chunked", recording)

        read, fake = read_remote("cube.gcode", ORCA, ignore_range=True)

        assert read is None
        assert len(fake.ranges) == 1  # given up on at the first answer
        assert chunks == []

    def test_a_redirect_is_not_followed_and_the_key_goes_nowhere_else(self):
        async def scenario():
            elsewhere = FakeMoonraker()
            other_url = await elsewhere.start()
            elsewhere.files["cube.gcode"] = ORCA
            redirected: list = []

            async def redirect(request):
                redirected.append(request.path)
                raise web.HTTPFound(f"{other_url}{request.path}")

            app = web.Application()
            app.router.add_get("/server/files/gcodes/{path:.+}", redirect)
            server = TestServer(app)
            await server.start_server()
            try:
                url = str(server.make_url("")).rstrip("/")
                reader = remote(url, api_key="mrk-key")
                read = await reader.read(no_calls, job("cube.gcode", ORCA))
                thumbnail = None
                with contextlib.suppress(ImageUnavailable):
                    thumbnail = await fetch_image(
                        f"{url}/server/files/gcodes/t.png", timeout=5, headers={"X-Api-Key": "k"}
                    )
                return read, thumbnail, redirected, elsewhere.ranges
            finally:
                await server.close()
                await elsewhere.close()

        read, thumbnail, redirected, reached = asyncio.run(scenario())

        assert read is None and thumbnail is None
        assert redirected  # asked, and answered with a redirect
        assert reached == []

    def test_inconsistent_metadata_falls_back_to_a_bounded_tail(self):
        """A `gcode_end_byte` before `gcode_start_byte` can't be where the G-code ends."""
        the_job = job("cube.gcode", ORCA)
        the_job["metadata"]["gcode_end_byte"] = the_job["metadata"]["gcode_start_byte"] - 10

        read, fake = read_remote("cube.gcode", ORCA, the_job)

        size = len(ORCA)
        assert ranges(fake)[1] == (max(0, size - TAIL_FALLBACK_BYTES), size - 1)
        assert read.config_block == ORCA[gcode_metadata(ORCA)["gcode_end_byte"] :].decode()

    def test_a_file_that_isnt_gcode_is_never_requested(self):
        read, fake = read_remote("cube.ufp", ORCA, job("cube.ufp", ORCA))

        assert read is None
        assert fake.downloads == []

    def test_a_missing_file_reads_nothing(self):
        async def scenario():
            async with moonraker() as (fake, url):
                return await remote(url).read(no_calls, job("gone.gcode", ORCA))

        assert asyncio.run(scenario()) is None

    def test_a_binary_file_reads_nothing(self):
        data = b"GCDE\x01\x00\x00\x00" + bytes(range(256)) * 40 + b"\nG28\n; a = 1\n"
        read, _ = read_remote("cube.gcode", data, job("cube.gcode", data, gcode_end_byte=40))

        assert read is None


def older(data: bytes) -> dict:
    """A job whose metadata came from Moonraker v0.9.3, which counts characters."""
    the_job = job("cube.gcode", data)
    the_job["metadata"].update(gcode_metadata(data, moonraker="v0.9.3"))
    return the_job


def assert_whole_lines_of_the_block(block: str, data: bytes) -> None:
    true_tail = data[gcode_metadata(data)["gcode_end_byte"] :].decode()
    assert block.lstrip("\r\n").startswith(";"), block[:80]
    assert true_tail.endswith(block)
    cut = len(true_tail) - len(block)
    assert cut == 0 or true_tail[cut - 1] in "\r\n", "the block starts mid-line"


class TestOlderMoonraker:
    """Moonraker v0.9.3 and older count `gcode_end_byte` in characters, so after non-ASCII text
    or CRLF line endings it points past where the G-code ends, into the settings block. The read
    still never starts mid-line: a line it cuts is dropped, never sent unscrubbed."""

    def test_non_ascii_in_the_settings_never_leaves_a_cut_secret(self):
        head = ORCA[: gcode_metadata(ORCA)["gcode_end_byte"]]
        prefix = b"; EXECUTABLE_BLOCK_END\n; printhost_apikey = "
        notes = "\u6e2c" * ((len(prefix) + 4) // 2)  # 3 bytes, 1 character each
        data = head + prefix + b"SECRETKEY123\n; printer_notes = " + notes.encode() + b"\n"
        metadata = gcode_metadata(data, moonraker="v0.9.3")
        landing = metadata["gcode_end_byte"] - len(head)
        assert len(prefix) < landing < len(prefix) + len("SECRETKEY123")  # mid-secret

        read, _ = read_remote("cube.gcode", data, older(data))

        assert_whole_lines_of_the_block(read.config_block, data)
        body = json.dumps(request_body(None, read))
        assert "KEY123" not in body and "SECRET" not in body

    def test_crlf_line_endings(self):
        data = ORCA.replace(b"\n", b"\r\n")

        read, fake = read_remote("cube.gcode", data, older(data))

        assert_whole_lines_of_the_block(read.config_block, data)
        assert SECRET not in json.dumps(request_body(None, read))
        assert "; printhost_apikey =\r\n" in request_body(None, read)["configBlock"]


class TestLocal:
    def read(self, tmp_path, monkeypatch, name, data, *, name_in_job=None, **metadata):
        root = tmp_path / "gcodes"
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_bytes(data)
        spans = []
        original = slicer_module.read_range

        async def recording(path, start, end, expected_size):
            spans.append((start, end - 1))
            return await original(path, start, end, expected_size)

        monkeypatch.setattr(slicer_module, "read_range", recording)

        async def call(method, params=None):
            assert method == "server.files.roots"
            return [{"name": "gcodes", "path": str(root)}]

        reader = MoonrakerSlicerFiles(
            "voron", MoonrakerImages("voron", url=None, socket=tmp_path / "moonraker.sock")
        )
        the_job = job(name_in_job or name, data, **metadata)
        return asyncio.run(reader.read(call, the_job)), spans

    @pytest.mark.parametrize("data", [ORCA, PRUSA])
    def test_reads_the_same_ranges_from_the_file(self, tmp_path, monkeypatch, data):
        read, spans = self.read(tmp_path, monkeypatch, "parts/cube.gcode", data)

        metadata = gcode_metadata(data)
        end = metadata["gcode_end_byte"]
        assert spans == [(0, metadata["gcode_start_byte"] - 1), (end - 1, len(data) - 1)]
        assert_no_toolpaths(spans, data)
        assert read.config_block == data[end:].decode()

    def test_a_file_changed_since_the_job_started_isnt_read(self, tmp_path, monkeypatch):
        read, _ = self.read(tmp_path, monkeypatch, "cube.gcode", ORCA, size=len(ORCA) + 1)

        assert read is None

    def test_nothing_outside_the_gcodes_folder(self, tmp_path, monkeypatch):
        (tmp_path / "secret.gcode").write_bytes(ORCA)

        read, spans = self.read(
            tmp_path, monkeypatch, "cube.gcode", ORCA, name_in_job="../secret.gcode"
        )

        assert read is None
        assert spans == []


class TestMetadata:
    def test_from_a_real_u1_history_entry(self):
        history = json.loads((FIXTURES / "moonraker" / "u1" / "history.json").read_text())
        jobs = history["result"]["jobs"] if "result" in history else history["jobs"]

        metadata = slicer_metadata(jobs[0]["metadata"])

        assert metadata == SlicerMetadata(
            slicer="SnapmakerOrca",
            slicer_version="2.4.0",
            layer_height_mm=0.16,
            first_layer_height_mm=0.2,
            nozzle_diameter_mm=0.4,
            filament_name=jobs[0]["metadata"]["filament_name"],
            filament_type="PLA;PLA;PLA;PLA",
            first_layer_nozzle_temperature_c=220.0,
            first_layer_bed_temperature_c=65.0,
        )

    def test_none_without_any(self):
        assert slicer_metadata({}) is None
        assert slicer_metadata({"size": 10, "thumbnails": []}) is None

    def test_an_unknown_slicer_is_no_slicer(self):
        # Moonraker's word for a slicer it can't identify, such as QIDI Studio's (#81).
        metadata = slicer_metadata(
            {"slicer": "Unknown", "slicer_version": "UNKNOWN", "layer_height": 0.2}
        )

        assert metadata == SlicerMetadata(layer_height_mm=0.2)
        assert slicer_metadata({"slicer": "unknown"}) is None
        body = request_body(metadata, None)
        assert body is None or "slicer" not in body.get("metadata", {})

    def test_odd_values_are_left_out(self):
        metadata = slicer_metadata({"slicer": 3, "layer_height": "x", "nozzle_diameter": True})
        assert metadata is None


async def _bridge_print(tmp_path: Path, data: bytes, *, slicer_settings: bool = True):
    moonraker = FakeMoonraker()
    api = FakePrintLogApi()
    moonraker_url, api_url = await moonraker.start(), await api.start()
    moonraker.files["cube.gcode"] = data
    config = helpers.write_config(tmp_path, moonraker_url, api_url)
    if not slicer_settings:
        with config.open("a", encoding="utf-8") as f:
            f.write("slicer_settings = false\n")
    metadata = {**gcode_metadata(data), "slicer": "OrcaSlicer", "estimated_time": 600.0}
    try:
        async with helpers.bridge(
            config,
            connected=lambda: moonraker.client_count == 1,
            disconnected=lambda: moonraker.client_count == 0,
        ):
            started = await moonraker.start_job("cube.gcode", metadata)
            await eventually(lambda: api.prints, 10)
            if slicer_settings:
                await eventually(lambda: api.slicer_records, 10)
            await moonraker.finish_job(started)
            await eventually(lambda: api.prints[1]["status"] == 3, 10)
            # Moonraker restarts and the bridge reads the history again: nothing more is read.
            await moonraker.drop()
            await eventually(lambda: moonraker.client_count == 1, 10)
            await asyncio.sleep(0.3)
    finally:
        await moonraker.close()
        await api.close()
    return moonraker, api


class TestThroughTheBridge:
    @pytest.mark.parametrize("data", [ORCA, PRUSA], ids=["orca", "prusa"])
    def test_sent_once_scrubbed_and_only_the_ranges_read(self, tmp_path, data):
        moonraker, api = asyncio.run(_bridge_print(tmp_path, data))

        assert_no_toolpaths(ranges(moonraker), data)
        assert len(moonraker.ranges) == 2
        [(print_id, body)] = api.slicer_posts
        assert print_id == 1
        assert set(body) == {"header", "configBlock", "metadata"}
        assert SECRET not in json.dumps(body)
        assert "; print_host =\n" in body["configBlock"]
        assert "; printhost_apikey =\n" in body["configBlock"]
        assert "; layer_height = 0.2\n" in body["configBlock"]
        assert body["metadata"] == {"slicer": "OrcaSlicer"}

    def test_off_the_file_is_never_requested(self, tmp_path):
        moonraker, api = asyncio.run(_bridge_print(tmp_path, ORCA, slicer_settings=False))

        assert moonraker.ranges == []
        assert "cube.gcode" not in moonraker.downloads
        assert api.slicer_posts == []


class TestTracker:
    def test_reports_them_after_the_start_and_reads_nothing_until_asked(self):
        from session_helpers import running

        from printlog_bridge.adapters.moonraker.jobs import JobTracker
        from printlog_bridge.adapters.moonraker.session import Backoff, MoonrakerSession
        from printlog_bridge.core.events import JobSlicerSettings, JobStarted

        class Sink:
            def __init__(self) -> None:
                self.events: list = []

            async def emit(self, event) -> None:
                self.events.append(event)

            async def resume_after(self, printer):
                return None

        async def scenario():
            sink = Sink()
            async with moonraker() as (fake, url):
                fake.files["cube.gcode"] = ORCA
                images = MoonrakerImages("voron", url=url, socket=None)
                session = MoonrakerSession(
                    "voron",
                    url=url,
                    listener=JobTracker("voron", sink, images=images),
                    backoff=Backoff(initial=0.01, maximum=0.05),
                )
                async with running(session):
                    await eventually(lambda: fake.subscriptions)
                    await fake.start_job("cube.gcode", job("cube.gcode", ORCA)["metadata"])
                    await eventually(lambda: any(
                        isinstance(e, JobSlicerSettings) for e in sink.events
                    ))  # fmt: skip
                    await asyncio.sleep(0.1)
                    unread = list(fake.ranges)
                    [event] = [e for e in sink.events if isinstance(e, JobSlicerSettings)]
                    read = await event.read()
            return sink, event, unread, read

        sink, event, unread, read = asyncio.run(scenario())

        assert isinstance(sink.events[0], JobStarted)
        assert sink.events.index(event) > 0
        assert event.job_id == sink.events[0].job_id
        assert event.metadata == SlicerMetadata(slicer="OrcaSlicer")
        assert unread == []
        assert read.config_block and read.header


