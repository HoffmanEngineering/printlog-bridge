"""What the bridge sends of a print's slicer settings (#36): the scrubbing, the header and
settings block cut from what was read, and the request body.

The fixtures in `tests/fixtures/gcode/` are real slicer output from the Slic3r uploader's tests
(`PrintLog.SlicerSettings.Tests/TestData`): the PrusaSlicer file as it is, the OrcaSlicer one with
most of its toolpaths cut out.
"""

from __future__ import annotations

import time
from pathlib import Path

import pytest

from printlog_bridge.core.events import SlicerFile, SlicerMetadata
from printlog_bridge.core.slicer_settings import (
    CONFIG_BLOCK_MAX_BYTES,
    HEADER_MAX_BYTES,
    config_block_from,
    header_from,
    is_sensitive,
    request_body,
    scrub,
)

GCODE = Path(__file__).parent / "fixtures" / "gcode"
ORCA = (GCODE / "orcaslicer-2.2.0-rc-calibration-cube.gcode").read_bytes()
PRUSA = (GCODE / "prusaslicer-2.9.2-calibration-cube.gcode").read_bytes()


API_LINE_BREAKS = ("\r", "\n", "\r\n", "\f", "\x85", "\u2028", "\u2029")


class TestScrub:
    @pytest.mark.parametrize(
        "key",
        [
            "print_host", "printhost_apikey", "printhost_password", "printhost_user",
            "printhost_cafile", "octoprint_apikey", "api_key", "moonraker_api_key", "password",
            "mqtt_passwd", "access_token", "client_secret", "username", "cookie_jar",
            "credentials", "authorization_header", "bbl_access_code", "post_process",
            "POST_PROCESS", "Print_Host",
        ],
    )  # fmt: skip
    def test_blanks_the_value_of_a_host_or_credential_key(self, key):
        assert is_sensitive(key)
        assert scrub(f"; {key} = hunter2\n") == f"; {key} =\n"

    @pytest.mark.parametrize(
        "key",
        ["layer_height", "host_type", "slowdown_for_curled_perimeters", "nozzle_temperature"],
    )
    def test_keeps_everything_else(self, key):
        assert not is_sensitive(key)
        assert scrub(f"; {key} = 0.2\n") == f"; {key} = 0.2\n"

    def test_keeps_the_key_and_every_other_character(self):
        text = "; layer_height = 0.2\r\n;print_host:  http://pi:pw@voron.local\r\n; infill = 15%"
        assert scrub(text) == "; layer_height = 0.2\r\n;print_host:\r\n; infill = 15%"

    @pytest.mark.parametrize(
        "brk", ["\r", "\n", "\r\n", "\f", "\v", "\x1c", "\x1d", "\x1e", "\x85", "\u2028", "\u2029"]
    )
    def test_every_line_break_python_knows_ends_a_line(self, brk):
        """`str.splitlines()`'s terminators, a superset of the API's: a CR-only block can't hide
        a key on what the API reads as its own line. Where the API reads on (`\\v`, `\\x1c`...),
        the value is blanked through to where the API's line ends."""
        text = brk.join(["; layer_height = 0.2", "; printhost_apikey = SECRET", "; a = 1"])
        scrubbed = scrub(text)
        assert "SECRET" not in scrubbed
        if brk in API_LINE_BREAKS:
            assert scrubbed == brk.join(["; layer_height = 0.2", "; printhost_apikey =", "; a = 1"])
        else:
            assert scrubbed == brk.join(["; layer_height = 0.2", "; printhost_apikey ="])

    def test_a_value_holding_a_break_the_api_doesnt_read_as_one_is_blanked_whole(self):
        """The API reads `\\v` as part of the line, so the whole of it is the key's value."""
        assert scrub("; api_key = SECRET\vMORE\n; a = 1") == "; api_key =\n; a = 1"

    def test_lines_that_arent_settings_are_left_alone(self):
        text = "G1 X10 ; password = no\n;password\n; token\nM104 S200\n"
        assert scrub(text) == text

    def test_is_linear_on_512_kb(self):
        """A long line, many lines, and many sensitive keys each take next to no time."""
        shapes = [
            "; " + "a" * CONFIG_BLOCK_MAX_BYTES,
            "; k = v\r" * (CONFIG_BLOCK_MAX_BYTES // 8),
            "; token = x\v" * (CONFIG_BLOCK_MAX_BYTES // 12),
            ";" * CONFIG_BLOCK_MAX_BYTES,
            "\r\n" * (CONFIG_BLOCK_MAX_BYTES // 2),
        ]
        for text in shapes:
            began = time.perf_counter()
            scrub(text)
            assert time.perf_counter() - began < 1.0

    def test_the_fixtures_post_process_and_printhost_values_are_blanked(self):
        block = scrub(config_block_from(ORCA[11609:]))
        assert "C:\\\\Users" not in block
        assert "; post_process =\n" in block
        assert "; printhost_authorization_type =\n" in block
        assert "; layer_height = 0.2\n" in block


class TestHeader:
    def test_orca_is_cut_at_the_header_block_end(self):
        header = header_from(ORCA[:8045])
        assert header.startswith("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.2.0-rc")
        assert header.endswith("; HEADER_BLOCK_END")
        assert "thumbnail" not in header

    def test_prusa_is_its_first_line(self):
        assert header_from(PRUSA[:303]) == (
            "; generated by PrusaSlicer 2.9.2 on 2026-09-13 at 12:26:02 UTC"
        )

    def test_nothing_without_text(self):
        assert header_from(b"") is None
        assert header_from(b"\x00\x01binary") is None


class TestConfigBlock:
    def test_from_the_end_of_the_gcode(self):
        block = config_block_from(PRUSA[1926:])
        assert block.startswith("; objects_info =")
        assert "; prusaslicer_config = end" in block

    def test_a_read_that_starts_mid_line_drops_the_partial_line(self):
        assert config_block_from(b"ue = 1\n; a = 2\n", starts_mid_line=True) == "; a = 2\n"

    def test_a_read_that_may_hold_toolpaths_keeps_only_what_follows_the_last_command(self):
        data = b"G1 X1\nG1 X2 ; SECRET\n; done\n; a = 2\n"
        block = config_block_from(data, starts_mid_line=True, after_gcode=True)
        assert block == "; done\n; a = 2\n"

    def test_nothing_from_binary_or_blank(self):
        assert config_block_from(b"\x00\x01\x02") is None
        assert config_block_from(b"\n\n") is None


METADATA = SlicerMetadata(
    slicer="OrcaSlicer",
    slicer_version="2.2.0",
    layer_height_mm=0.2,
    first_layer_height_mm=0.2,
    nozzle_diameter_mm=0.4,
    filament_name="Generic PLA",
    filament_type="PLA",
    first_layer_nozzle_temperature_c=220.0,
    first_layer_bed_temperature_c=60.0,
)


class TestRequestBody:
    def test_metadata_under_the_apis_names(self):
        assert request_body(METADATA, None) == {
            "metadata": {
                "slicer": "OrcaSlicer",
                "slicerVersion": "2.2.0",
                "layerHeightMm": 0.2,
                "firstLayerHeightMm": 0.2,
                "nozzleDiameterMm": 0.4,
                "filamentName": "Generic PLA",
                "filamentType": "PLA",
                "firstLayerNozzleTemperatureC": 220.0,
                "firstLayerBedTemperatureC": 60.0,
            }
        }

    def test_the_block_and_header_scrubbed(self):
        file = SlicerFile(header="; print_host = h\n", config_block="; api_key = k\n; a = 1\n")
        assert request_body(None, file) == {
            "header": "; print_host =\n",
            "configBlock": "; api_key =\n; a = 1\n",
        }

    def test_what_the_api_would_refuse_is_left_out_rather_than_failing_the_whole(self):
        """A value over the API's length or outside its range would be a 400 for everything."""
        odd = SlicerMetadata(
            slicer="x" * 60,
            filament_name="PLA;" * 100,
            layer_height_mm=float("nan"),
            nozzle_diameter_mm=-1.0,
            first_layer_bed_temperature_c=2000.0,
            first_layer_nozzle_temperature_c=float("inf"),
        )
        metadata = request_body(odd, SlicerFile(config_block="; a = 1\n"))["metadata"]
        assert metadata == {"slicer": "x" * 50, "filamentName": ("PLA;" * 100)[:200]}

    def test_nothing_the_api_could_record_is_nothing_to_send(self):
        """Metadata alone needs the slicer's name."""
        assert request_body(None, None) is None
        assert request_body(SlicerMetadata(layer_height_mm=0.2), None) is None
        assert request_body(SlicerMetadata(), SlicerFile()) is None
        assert request_body(SlicerMetadata(layer_height_mm=0.2), SlicerFile(header="; h")) is None

    def test_never_over_the_apis_caps(self):
        """Bytes that decode to a replacement character grow; the body is cut to fit."""
        block = "; a = \ufffd\n" * (CONFIG_BLOCK_MAX_BYTES // 8)
        header = "\ufffd" * HEADER_MAX_BYTES
        body = request_body(None, SlicerFile(header=header, config_block=block))
        assert len(body["configBlock"].encode()) <= CONFIG_BLOCK_MAX_BYTES
        assert body["configBlock"].endswith("; a = \ufffd\n")
        assert body["configBlock"].startswith("; a = ")
        assert len(body["header"].encode()) <= HEADER_MAX_BYTES
