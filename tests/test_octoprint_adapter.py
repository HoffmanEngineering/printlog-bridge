class TestRun:
    def test_a_print_from_start_to_finish(self, tmp_path):
        sink, report = Sink(), Report()

        async def scenario():
            async with octoprint() as fake:
                fake.add("folder/Benchy.gcode", make_gcode(pad=600_000), tools=3)
                adapter = adapter_for(fake)
                adapter.use_state(PrinterState.load(tmp_path, "ender"))
                async with running(adapter, sink, report):
                    await eventually(lambda: report.states)
                    await fake.print_file("folder/Benchy.gcode")
                    await eventually(lambda: sink.of(JobStarted))
                    fake.completion = 40.0
                    await asyncio.sleep(0.2)
                    await fake.done()
                    await eventually(lambda: sink.of(JobFinished))
                    await asyncio.sleep(0.2)  # later statuses don't start it again
                return fake

        fake = asyncio.run(scenario())

        [start] = sink.of(JobStarted)
        assert start.file_name == "Benchy.gcode"
        assert start.job_id == f"{int(start.started_at.timestamp())}-Benchy"
        assert start.estimated_filament_g_by_slot == {0: 4.1, 2: 1.25}
        assert start.estimated_filament_mm == 1788.0  # the slicer's, not OctoPrint's analysis
        assert start.estimated_duration_s == 642.0
        [finished] = sink.of(JobFinished)
        assert finished.outcome is JobOutcome.COMPLETED
        assert finished.filament_g == {0: 4.1, 2: 1.25}
        assert finished.filament_mm == {0: 1370.0, 2: 418.0}
        assert finished.usage_estimated is True
        thumbnail = [e for e in sink.of(JobImage) if e.kind is ImageKind.THUMBNAIL]
        assert asyncio.run(thumbnail[0].fetch()) == PNG  # the largest
        [settings] = sink.of(JobSlicerSettings)
        assert settings.metadata.slicer == "PrusaSlicer"
        assert settings.metadata.filament_type == "PETG"
        read = asyncio.run(settings.read())
        assert "printhost_apikey" in read.config_block and "SECRET-GCODE" not in read.config_block
        assert report.models == ["ENDER3"]
        assert report.hosts == [("OctoPrint", VERSION)]
        assert fake.throttles == [4]
        ranges = [h.get("Range") for _, p, h in fake.requests if p.startswith("/downloads/")]
        assert ranges[0] == "bytes=0-262143" and ranges[1].startswith("bytes=")
        assert fake.methods == {"GET"}  # beyond the login, nothing but reads

