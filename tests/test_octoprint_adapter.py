def thumbnail_block(width: int, height: int, data: bytes, kind: str = "") -> str:
    encoded = base64.b64encode(data).decode()
    lines = [encoded[i : i + 78] for i in range(0, len(encoded), 78)]
    tag = f"thumbnail_{kind}" if kind else "thumbnail"
    body = "".join(f"; {line}\n" for line in lines)
    return f";\n; {tag} begin {width}x{height} {len(encoded)}\n{body}; {tag} end\n;\n"


def make_gcode(grams: str = "4.10, 0, 1.25", mm: str = "1370.0, 0, 418.0", pad: int = 0) -> bytes:
    head = (
        "; generated by PrusaSlicer 2.9.2+win64 on 2026-10-27 at 10:00:00 UTC\n\n"
        + thumbnail_block(16, 16, b"\x89PNG\r\n\x1a\nsmall")
        + thumbnail_block(220, 124, PNG)
        + "\n"
    )
    body = "G1 X10 Y10 E.5 ; SECRET-GCODE\n" * max(1, pad // 30)
    tail = (
        f"; filament used [mm] = {mm}\n; filament used [g] = {grams}\n"
        "; estimated printing time (normal mode) = 1h 2m 3s\n\n"
        "; prusaslicer_config = begin\n; layer_height = 0.2\n; nozzle_diameter = 0.4,0.4,0.4\n"
        "; filament_type = PETG;PLA;PLA\n; printhost_apikey = SECRET-KEY\n"
        "; printer_model = ENDER3\n; prusaslicer_config = end\n"
    )
    return (head + body + tail).encode()


def options(**more) -> dict[str, str]:
    return {"url": "http://127.0.0.1:5000", "api_key": API_KEY, **more}


class TestConfig:
    def test_reads_its_options(self):
        adapter = OctoPrintAdapter.from_config(
            "ender", options(url="http://octopi.local:5000/octoprint/", files="no")
        )
        assert adapter.url == "http://octopi.local:5000/octoprint"
        assert adapter.files is False and adapter.snapshots is True
        assert adapter.describe() == "octoprint, http://octopi.local:5000/octoprint"
        assert API_KEY not in adapter.describe()
        assert ADAPTERS["octoprint"] is OctoPrintAdapter
        assert adapter.credential_fields() == ("api_key",)

    def test_the_key_is_used_as_given(self):
        adapter = OctoPrintAdapter.from_config("ender", options(api_key=" k3y "))
        assert adapter.api_key == " k3y "

    @pytest.mark.parametrize(
        ("option", "value"),
        [
            ("url", "octopi.local"),
            ("url", "ftp://octopi.local"),
            ("url", "http://octopi.local:99999"),
            ("url", "http://pi:raspberry@octopi.local"),
            ("api_key", "  "),
            ("files", "maybe"),
            ("snapshots", "maybe"),
        ],
    )
    def test_a_bad_value_is_refused(self, option, value):
        with pytest.raises(ConfigError, match=option):
            OctoPrintAdapter.from_config("ender", options(**{option: value}))

    def test_url_and_key_are_needed(self):
        with pytest.raises(ConfigError, match="url"):
            OctoPrintAdapter.from_config("ender", {"api_key": "k"})
        with pytest.raises(ConfigError, match="Application Keys"):
            OctoPrintAdapter.from_config("ender", {"url": "http://octopi.local"})

    def test_an_unknown_option_is_refused(self):
        with pytest.raises(ConfigError, match="apikey"):
            OctoPrintAdapter.from_config("ender", options(apikey="x"))

    def test_a_printer_from_the_app(self):
        made = OctoPrintAdapter.app_options("192.168.1.50", 5000, None, {"api_key": " k "})
        assert made == {"url": "http://192.168.1.50:5000", "api_key": " k "}
        assert OctoPrintAdapter.app_options("fd00::5", 80, None, {"api_key": "k"})["url"] == (
            "http://[fd00::5]"
        )
        with pytest.raises(NeedsCredentials) as missing:
            OctoPrintAdapter.app_options("192.168.1.50", 80, None, {})
        assert missing.value.fields == ("api_key",)
        assert OctoPrintAdapter.app_secrets == ("api_key",)
        adapter = OctoPrintAdapter.from_config("app-1", made)
        assert adapter.watches(Found("octoprint", "192.168.1.50", 5000))
        assert not adapter.watches(Found("octoprint", "192.168.1.50", 80))
        assert adapter.found_entry() == Found("octoprint", "192.168.1.50", 5000)

    def test_serves_its_uploads_folder(self, tmp_path):
        base = tmp_path / ".octoprint"
        (base / "uploads").mkdir(parents=True)
        (base / "config.yaml").write_text("{}\n")
        adapter = OctoPrintAdapter.from_config("ender", options())
        assert "OctoPrint" in adapter.serves(base / "uploads" / "printlog-bridge.cfg")
        assert adapter.serves(tmp_path / "printlog-bridge.cfg") is None


