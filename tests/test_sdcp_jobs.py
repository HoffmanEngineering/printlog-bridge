"""The SDCP job tracker on its own, fed status messages as an Elegoo Centauri Carbon pushes them
(`tests/fake_elegoo.py` says where its shape comes from; none is recorded yet, #94)."""

from __future__ import annotations

import asyncio
from datetime import datetime, timezone

from printlog_bridge.adapters.common.slicer_meta import JobFile
from printlog_bridge.adapters.sdcp.jobs import KEY, JobTracker
from printlog_bridge.core.current_job import CurrentJob
from printlog_bridge.core.events import (
    ImageKind,
    JobFinished,
    JobImage,
    JobOutcome,
    JobSlicerSettings,
    JobStarted,
    SlicerFile,
)
from printlog_bridge.core.state import MemoryState, PrinterState

T0 = 1793151018
"""The printer's clock when the first status of a test arrives."""
FILE = "/local/Benchy.gcode"


class Sink:
    def __init__(self) -> None:
        self.events: list = []

    async def emit(self, event) -> None:
        self.events.append(event)

    def of(self, kind):
        return [e for e in self.events if isinstance(e, kind)]


class Clock:
    """The bridge's clock, `skew` seconds behind the printer's."""

    def __init__(self, skew: float = 0.0) -> None:
        self.now = float(T0)
        self.skew = skew

    def __call__(self) -> datetime:
        return datetime.fromtimestamp(self.now - self.skew, timezone.utc)


class Files:
    """A reader that found the slicer's estimate."""

    def __init__(self, grams: float = 20.0, mm: float = 6000.0) -> None:
        self.reads: list[str] = []
        self.grams, self.mm = grams, mm

    async def read(self, path: str) -> JobFile:
        self.reads.append(path)
        return JobFile(grams={0: self.grams}, mm={0: self.mm}, duration_s=3000.0)


def status(
    t: float,
    sub: int = 13,
    *,
    path: str = FILE,
    task: str = "task-1",
    progress: int = 10,
    layer: int | None = None,
    ticks: int | None = None,
    machine: int | None = None,
    total_s: int = 3600,
    layers: int = 200,
) -> dict:
    if machine is None:
        machine = 0 if sub in (0, 8, 9, 14) else 1
    return {
        "Status": {
            "CurrentStatus": [machine],
            "TempOfNozzle": 210.0,
            "PrintInfo": {
                "Status": sub,
                "CurrentLayer": layer if layer is not None else layers * progress // 100,
                "TotalLayer": layers,
                "CurrentTicks": ticks if ticks is not None else total_s * progress // 100,
                "TotalTicks": total_s,
                "Filename": path,
                "TaskId": task,
                "PrintSpeedPct": 100,
                "Progress": progress,
            },
        },
        "MainboardID": "board",
        "TimeStamp": int(t),
        "Topic": "sdcp/status/board",
    }


def tracker(state=None, clock=None, files=None, sink=None):
    sink = sink or Sink()
    clock = clock or Clock()
    current = CurrentJob(state or MemoryState(), clock=clock)
    return JobTracker("cc", sink, current, files=files, clock=clock), sink, clock


def feed(t: JobTracker, *messages) -> None:
    async def go():
        for message in messages:
            await t.on_status(message)

    asyncio.run(go())


class TestLive:
    def test_a_print_from_start_to_completion(self):
        t, sink, clock = tracker(files=Files())
        clock.now = T0 + 600
        feed(
            t,
            status(T0 + 600, 13, progress=10, ticks=600),
            status(T0 + 3000, 13, progress=80),
            status(T0 + 3700, 9, progress=100),
            status(T0 + 3701, 9, progress=100, machine=0),
        )
        [start] = sink.of(JobStarted)
        assert start.started_at == datetime.fromtimestamp(T0, timezone.utc)
        assert start.job_id == f"{T0}-Benchy"
        assert start.file_name == "Benchy.gcode"
        assert start.estimated_duration_s == 3000.0  # the file's, before the printer's
        assert start.estimated_filament_g == 20.0
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED
        assert done.finished_at == datetime.fromtimestamp(T0 + 3700, timezone.utc)
        assert done.duration_s == 3700
        assert done.filament_g == {0: 20.0} and done.usage_estimated is True
        assert done.note is None

    def test_the_files_thumbnail_and_header_go_with_the_start(self):
        class WithThumbnail(Files):
            async def read(self, path: str) -> JobFile:
                found = await super().read(path)
                found.thumbnail = b"\x89PNG\r\n\x1a\nthumb"
                found.settings = SlicerFile(header="; generated by ElegooSlicer 1.1.5")
                return found

        t, sink, _ = tracker(files=WithThumbnail())
        feed(t, status(T0, 13))
        [start] = sink.of(JobStarted)
        [image] = sink.of(JobImage)
        assert image.kind is ImageKind.THUMBNAIL and image.job_id == start.job_id
        assert asyncio.run(image.fetch()) == b"\x89PNG\r\n\x1a\nthumb"
        [settings] = sink.of(JobSlicerSettings)
        assert asyncio.run(settings.read()).header.startswith("; generated by ElegooSlicer")

    def test_without_a_file_the_printers_estimate_is_the_duration(self):
        t, sink, _ = tracker()
        feed(t, status(T0, 13, total_s=5400), status(T0 + 10, 9, progress=100))
        [start] = sink.of(JobStarted)
        assert start.estimated_duration_s == 5400
        assert start.estimated_filament_g is None
        [done] = sink.of(JobFinished)
        assert done.filament_g == {} and done.filament_mm == {}
        assert done.usage_estimated is False

    def test_the_end_is_on_the_printers_clock(self):
        t, sink, clock = tracker(clock=Clock(skew=300))  # the bridge is 5 minutes behind
        feed(t, status(T0, 13, progress=0, ticks=0), status(T0 + 60, 9, progress=100))
        [start] = sink.of(JobStarted)
        [done] = sink.of(JobFinished)
        assert start.started_at == datetime.fromtimestamp(T0, timezone.utc)
        assert done.finished_at == datetime.fromtimestamp(T0 + 60, timezone.utc)

    def test_a_cancel_charges_what_was_printed(self):
        t, sink, _ = tracker(files=Files(grams=40.0, mm=12000.0))
        feed(
            t,
            status(T0, 13, progress=5),
            status(T0 + 100, 13, progress=25),
            status(T0 + 110, 7, progress=25),
            status(T0 + 120, 8, progress=25),
        )
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.CANCELLED
        assert done.filament_g == {0: 10.0} and done.filament_mm == {0: 3000.0}
        assert done.usage_estimated is True

    def test_a_cancel_that_clears_the_file_name_still_ends_the_job(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, progress=30),
            status(T0 + 10, 7, progress=30),
            status(T0 + 20, 8, path="", task="", progress=0),
        )
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.CANCELLED
        assert done.finished_at == datetime.fromtimestamp(T0 + 20, timezone.utc)

    def test_an_error_is_a_failure(self):
        t, sink, _ = tracker(files=Files(grams=10.0))
        feed(t, status(T0, 13, progress=50), status(T0 + 10, 14, progress=50))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.FAILED
        assert done.filament_g == {0: 5.0}
        assert "error" in done.note

    def test_preparing_never_starts_a_job(self):
        """The start routine (homing, preheating, leveling, "print start") still shows the last
        job's file and task; only printing (or a pause) starts one."""
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 9, path="/local/Old.gcode", task="old", progress=100),
            status(T0 + 5, 16, path="/local/Old.gcode", task="old", progress=100),
            status(T0 + 6, 1, path="/local/Old.gcode", task="old", progress=100),
            status(T0 + 7, 18, path="/local/Old.gcode", task="old", progress=100),
        )
        assert sink.events == []
        feed(t, status(T0 + 60, 13, path="/local/New.gcode", task="new", progress=0, ticks=0))
        [start] = sink.of(JobStarted)
        assert start.file_name == "New.gcode"
        assert start.started_at == datetime.fromtimestamp(T0 + 60, timezone.utc)

    def test_an_idle_printer_starts_nothing(self):
        t, sink, _ = tracker()
        feed(t, status(T0, 0, path="", task="", progress=0))
        assert sink.events == []

    def test_a_long_pause_doesnt_split_the_job(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, progress=10),
            status(T0 + 100, 5, progress=40),
            status(T0 + 101, 6, progress=40),
            # Hours later, the nozzle heats again before printing carries on.
            status(T0 + 9 * 3600, 16, progress=40),
            status(T0 + 9 * 3600 + 60, 12, progress=40),
            status(T0 + 9 * 3600 + 90, 13, progress=41, ticks=1500),
            status(T0 + 12 * 3600, 9, progress=100),
        )
        assert len({s.job_id for s in sink.of(JobStarted)}) == 1
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED
        assert done.duration_s == 12 * 3600 + 360  # from T0 less its 360 s printed

    def test_a_filament_change_mid_print_carries_on(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, progress=10),
            status(T0 + 10, 25, progress=10),
            status(T0 + 20, 26, progress=10),
            status(T0 + 30, 13, progress=11),
        )
        assert len(sink.of(JobStarted)) == 1 and not sink.of(JobFinished)

    def test_a_late_status_of_the_job_that_ended_starts_nothing(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, progress=90),
            status(T0 + 10, 9, progress=100),
            status(T0 + 11, 13, progress=100),
        )
        assert len(sink.of(JobStarted)) == 1 and len(sink.of(JobFinished)) == 1

    def test_the_same_file_printed_again_is_a_new_job(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, task="a", progress=90),
            status(T0 + 10, 9, task="a", progress=100),
            status(T0 + 100, 16, task="a", progress=100),
            status(T0 + 200, 13, task="b", progress=0, ticks=0),
        )
        starts = sink.of(JobStarted)
        assert len(starts) == 2 and starts[0].job_id != starts[1].job_id

    def test_another_task_while_one_runs_ends_the_first_by_its_progress(self):
        t, sink, _ = tracker()
        feed(
            t,
            status(T0, 13, task="a", progress=45),
            status(T0 + 500, 13, path="/local/Other.gcode", task="b", progress=1, ticks=5),
        )
        finished = sink.of(JobFinished)
        assert [f.outcome for f in finished] == [JobOutcome.CANCELLED]
        assert [s.file_name for s in sink.of(JobStarted)] == ["Benchy.gcode", "Other.gcode"]

    def test_a_status_with_only_what_changed_is_merged(self):
        t, sink, _ = tracker()
        first = status(T0, 13, progress=10)
        only_progress = {
            "Status": {"PrintInfo": {"Progress": 60, "CurrentLayer": 120}},
            "TimeStamp": T0 + 100,
        }
        only_state = {"Status": {"PrintInfo": {"Status": 9}}, "TimeStamp": T0 + 200}
        feed(t, first, only_progress, only_state)
        [start] = sink.of(JobStarted)
        assert start.file_name == "Benchy.gcode"
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED

    def test_the_printer_state_is_reported_in_words(self):
        states: list[str] = []

        class Report:
            def printer_state(self, state):
                states.append(state)

        sink, clock = Sink(), Clock()
        t = JobTracker("cc", sink, CurrentJob(MemoryState(), clock=clock), report=Report(),
                       clock=clock)  # fmt: skip
        feed(t, status(T0, 13), status(T0 + 1, 6), status(T0 + 2, 0, path=""))
        assert states == ["printing", "paused", "idle"]


class TestReconnects:
    def test_a_reconnect_mid_print_is_the_same_job(self, tmp_path):
        state = PrinterState.load(tmp_path, "cc")
        t, sink, _ = tracker(state)
        feed(t, status(T0, 13, progress=10))
        t.connected()
        feed(t, status(T0 + 900, 13, progress=50), status(T0 + 2000, 9, progress=100))
        assert len({s.job_id for s in sink.of(JobStarted)}) == 1
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED

    def test_a_bridge_restart_mid_print_keeps_the_job(self, tmp_path):
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"))
        feed(t, status(T0, 13, progress=10, ticks=360))
        kept = PrinterState.load(tmp_path, "cc").discovery[KEY]
        assert kept["path"] == FILE and kept["task_id"] == "task-1"

        # A new bridge, an hour later: the job is found by what was kept, not recomputed.
        again, sink2, clock = tracker(PrinterState.load(tmp_path, "cc"))
        clock.now = T0 + 3600
        feed(
            again,
            status(T0 + 3600, 13, progress=60, ticks=1000),
            status(T0 + 4000, 9, progress=100),
        )
        [start] = sink2.of(JobStarted)
        assert start.job_id == sink.of(JobStarted)[0].job_id
        [done] = sink2.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED
        assert done.duration_s == 4360  # from its start, kept: T0 less 360 s printing

    def test_a_job_paused_through_a_restart_is_the_same_job(self, tmp_path):
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"))
        feed(t, status(T0, 13, progress=10), status(T0 + 10, 6, progress=20))
        again, sink2, _ = tracker(PrinterState.load(tmp_path, "cc"))
        feed(again, status(T0 + 20 * 3600, 6, progress=20, ticks=50))
        assert [s.job_id for s in sink2.of(JobStarted)] == [sink.of(JobStarted)[0].job_id]
        assert not sink2.of(JobFinished)

    def test_an_end_missed_with_the_printer_saying_complete(self, tmp_path):
        t, sink, clock = tracker(PrinterState.load(tmp_path, "cc"))
        feed(t, status(T0, 13, progress=50))
        t.connected()
        clock.now = T0 + 7200
        feed(t, status(T0 + 7200, 9, progress=100))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED
        assert done.finished_at == datetime.fromtimestamp(T0, timezone.utc)  # last seen
        assert "wasn't connected" in done.note

    def test_an_end_missed_with_the_printer_in_error_is_a_failure(self, tmp_path):
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"), files=Files(grams=10.0))
        feed(t, status(T0, 13, progress=30))
        t.connected()
        feed(t, status(T0 + 7200, 14, progress=30))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.FAILED
        assert done.filament_g == {0: 3.0}

    def test_a_printer_that_rebooted_ends_the_job_by_its_progress(self, tmp_path):
        """Off or restarted is not an error: idle with nothing of the job left is decided by
        how far it got."""
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"), files=Files(grams=10.0))
        feed(t, status(T0, 13, progress=30), status(T0 + 60, 13, progress=40))
        t.connected()
        feed(t, status(T0 + 7200, 0, path="", task="", progress=0))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.CANCELLED
        assert done.filament_g == {0: 4.0}
        assert "how far it got" in done.note

    def test_a_job_seen_at_99_percent_before_a_reboot_is_complete(self, tmp_path):
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"), files=Files(grams=10.0))
        feed(t, status(T0, 13, progress=99))
        t.connected()
        feed(t, status(T0 + 7200, 0, path="", task="", progress=0))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED
        assert done.filament_g == {0: 10.0}

    def test_an_end_of_another_task_isnt_this_jobs(self, tmp_path):
        """The printer says how *its* last job ended: another task's cancel says nothing of
        this one, which is decided by its progress."""
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"))
        feed(t, status(T0, 13, task="a", progress=99))
        t.connected()
        feed(t, status(T0 + 7200, 8, path="/local/Other.gcode", task="b", progress=3))
        [done] = sink.of(JobFinished)
        assert done.outcome is JobOutcome.COMPLETED  # by its own 99%

    def test_after_a_restart_the_kept_start_gives_the_usage(self, tmp_path):
        t, sink, _ = tracker(PrinterState.load(tmp_path, "cc"), files=Files(grams=12.0))
        feed(t, status(T0, 13, progress=50))
        again, sink2, _ = tracker(PrinterState.load(tmp_path, "cc"))  # no reader now
        feed(again, status(T0 + 60, 8, progress=50))
        [done] = sink2.of(JobFinished)
        assert done.outcome is JobOutcome.CANCELLED
        assert done.filament_g == {0: 6.0}

    def test_the_ended_job_is_forgotten(self, tmp_path):
        state = PrinterState.load(tmp_path, "cc")
        t, _, _ = tracker(state)
        feed(t, status(T0, 13), status(T0 + 10, 9, progress=100))
        kept = PrinterState.load(tmp_path, "cc").discovery
        assert KEY not in kept and "current_job" not in kept
